function x = tsIntegrate(y, x0)
%TSINTEGRATE  Inverse of TSDIFF: reconstruct a series from its differences.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     y       Mx1 double [numeric,real,finite]
%       Differenced series.
%     x0      dx1 double [double]
%       Initial values per level returned by tsDiff.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     x       (M+d)x1 double [double]
%       Reconstructed original-scale series.
%
%   See also: tsDiff, tsForecast.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (tsmodels)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%   X = TSINTEGRATE(Y,X0) inverts Y=(1-B)^D X given the D initial values X0
%   returned by TSDIFF.  Base MATLAB only.
    y = y(:); x0 = x0(:);
    validateattributes(y,  {'numeric'}, {'vector','real','finite'});
    for i = numel(x0):-1:1
        x = x0(i) + [0; cumsum(y)];
        y = x;
    end
    if isempty(x0), x = y; end
end
