function [pacf, lags, conf] = tsPacf(x, maxLag, makePSD)
%TSPACF  Sample partial autocorrelation function (Durbin-Levinson, gap-aware).
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     x       Nx1 double [numeric,real,vector]
%       Time series; may contain NaN at missing timestamps.
%     maxLag  1x1 double [double]
%       (optional) Maximum lag. Default min(N-1,40).
%     makePSD 1x1 logical [logical]
%       (optional) If true, project the pairwise ACF onto the nearest
%       positive-semidefinite autocorrelation before the recursion (useful
%       under heavy gapping to guarantee |PACF|<=1). Default false.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     pacf    maxLag x1 double [double]
%       Sample PACF at lags 1..maxLag.
%     lags    maxLag x1 double [double]
%       Lag indices 1..maxLag.
%     conf    1x1 double [double]
%       +/- 95% white-noise band (uses smallest pair count).
%
%   See also: tsAcf, tsFitArima.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (tsmodels)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%   [PACF,LAGS,CONF] = TSPACF(X,MAXLAG) returns the sample PACF at lags
%   1..MAXLAG via the Durbin-Levinson recursion on the sample ACF.
%
%   Missing samples: X may contain NaN; the ACF is estimated pairwise-complete
%   (see TSACF). Note that a pairwise ACF is not guaranteed positive-definite,
%   so with many gaps the recursion can yield |PACF|>1; a warning is issued.
%   For estimation with gaps prefer TSFITARIMA (exact missing-data ML); use
%   this PACF for identification/diagnostics.  Base MATLAB only.
    x = x(:);
    validateattributes(x, {'numeric'}, {'vector','real'});
    N = numel(x);
    if nargin < 2 || isempty(maxLag), maxLag = min(N-1, 40); end
    if nargin < 3 || isempty(makePSD), makePSD = false; end
    maxLag = min(round(maxLag), N-1);

    [r, ~, ~, nPairs] = timeSeriesPreparation.tsmodels.tsAcf(x, maxLag);
    r = r(2:end);                             % rho_1..rho_maxLag
    if any(isnan(r))
        error('tsPacf:unobservableLag', ...
            'Some lags have no complete pairs; reduce MAXLAG or fill gaps.');
    end

    % Optional: project the (possibly non-PD, pairwise) ACF onto the nearest
    % valid positive-semidefinite autocorrelation before the recursion. Uses
    % alternating projection between the PSD cone and the unit-diagonal
    % Toeplitz set. Guarantees |PACF|<=1 and a well-posed Durbin-Levinson.
    if makePSD
        r = local_nearestPDacf([1; r(:)]);
        r = r(2:end);
    end

    pacf = zeros(maxLag, 1);
    phi  = zeros(maxLag, maxLag);
    if maxLag >= 1, phi(1,1) = r(1); pacf(1) = r(1); end
    for k = 2:maxLag
        den = 1 - phi(k-1, 1:k-1) * r(1:k-1);
        if abs(den) < eps, den = sign(den + eps)*eps; end
        phi(k,k) = (r(k) - phi(k-1, 1:k-1) * r(k-1:-1:1)) / den;
        phi(k, 1:k-1) = phi(k-1, 1:k-1) - phi(k,k) * phi(k-1, k-1:-1:1);
        pacf(k) = phi(k,k);
    end

    if any(abs(pacf) > 1)
        warning('tsPacf:nonPD', ...
            ['Pairwise ACF is not positive-definite (|PACF|>1 at some lag); ', ...
             'interpret with caution or fill gaps before identification.']);
    end
    lags = (1:maxLag)';
    conf = 1.96 / sqrt(max(min(nPairs(2:end)), 1));
end

% ======================================================================
function r = local_nearestPDacf(r0)
% Nearest positive-semidefinite autocorrelation sequence to r0 (r0(1)=1)
% by alternating projection: (i) clip eigenvalues of the Toeplitz matrix
% to >= 0, (ii) restore Toeplitz structure by averaging each diagonal and
% renormalising r(1)=1. Base MATLAB.
    r0 = r0(:); n = numel(r0); r = r0 / r0(1);
    for it = 1:100
        R = toeplitz(r);
        [V, D] = eig(0.5*(R + R'));
        d = max(real(diag(D)), 0);
        Rp = V * diag(d) * V';
        new = zeros(n,1);
        for k = 0:n-1
            new(k+1) = mean(diag(Rp, k));
        end
        new = new / new(1);
        if max(abs(new - r)) < 1e-10, r = new; break; end
        r = new;
    end
end
