function [best, table] = tsAutoArima(x, maxP, maxQ, d, varargin)
%TSAUTOARIMA  Grid search over (p,q) minimising an information criterion.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     x         Nx1 double [numeric,real,vector]
%       Series (NaN allowed with the default exact method).
%     maxP      1x1 double [double]
%       (optional) Maximum AR order. Default 3.
%     maxQ      1x1 double [double]
%       (optional) Maximum MA order. Default 3.
%     d         1x1 double [double]
%       (optional) Differencing order. Default 0.
%     varargin  name-value [mixed]
%       'Criterion'('aic'|'bic') plus any option forwarded to tsFitArima.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     best    1x1 struct [struct]
%       Best model (see tsFitArima).
%     table   Rx6 double [double]
%       Sorted rows [p q criterion aic bic logL].
%
%   See also: tsFitArima, tsForecast, tsModelDisp.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (tsmodels)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%   [BEST,TABLE] = TSAUTOARIMA(X,MAXP,MAXQ,D) fits every ARIMA(p,D,q) for
%   0<=p<=MAXP, 0<=q<=MAXQ (excluding p=q=0) and returns the best model.
%
%   Options:
%       'Criterion' 'aic' (default) | 'bic'
%       ...plus any option forwarded to TSFITARIMA (e.g. 'Constant').
%
%   TABLE columns: [p q criterion aic bic logL].
%
%   Base MATLAB only.
    if nargin < 2 || isempty(maxP), maxP = 3; end
    if nargin < 3 || isempty(maxQ), maxQ = 3; end
    if nargin < 4 || isempty(d),    d = 0;    end

    crit = 'aic';
    keep = {};
    i = 1;
    while i <= numel(varargin)
        if strcmpi(varargin{i},'Criterion')
            crit = lower(varargin{i+1}); i = i+2;
        else
            keep(end+1:end+2) = varargin(i:i+1); i = i+2; %#ok<AGROW>
        end
    end

    rows = [];
    models = {};
    for p = 0:maxP
        for q = 0:maxQ
            if p==0 && q==0, continue; end
            try
                mdl = timeSeriesPreparation.tsmodels.tsFitArima(x, p, d, q, keep{:});
                switch crit
                    case 'aic', c = mdl.aic;
                    case 'bic', c = mdl.bic;
                    otherwise, error('Unknown criterion');
                end
                rows(end+1,:) = [p q c mdl.aic mdl.bic mdl.logL]; %#ok<AGROW>
                models{end+1} = mdl; %#ok<AGROW>
            catch
                % skip non-converging orders
            end
        end
    end

    [~, ix] = sortrows(rows, 3);
    table = rows(ix,:);
    best  = models{ix(1)};
end
