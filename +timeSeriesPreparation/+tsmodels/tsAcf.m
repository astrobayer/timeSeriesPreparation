function [rho, lags, conf, nPairs] = tsAcf(x, maxLag)
%TSACF  Sample autocorrelation function (gap-aware).
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     x       Nx1 double [numeric,real,vector]
%       Time series; may contain NaN at missing timestamps (Inf not
%       allowed).
%     maxLag  1x1 double [double]
%       (optional) Maximum lag. Default min(N-1,40).
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     rho     (maxLag+1)x1 double [double]
%       Sample ACF, rho(1)=1. NaN at unobservable lags.
%     lags    (maxLag+1)x1 double [double]
%       Lag indices 0..maxLag.
%     conf    1x1 double [double]
%       +/- 95% white-noise band (uses lag-1 pair count).
%     nPairs  (maxLag+1)x1 double [double]
%       Number of complete (t,t+k) pairs per lag.
%
%   See also: tsPacf, tsFitArima, tsLjungBox.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (tsmodels)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%   [RHO,LAGS,CONF] = TSACF(X,MAXLAG) returns the sample ACF of vector X at
%   lags 0..MAXLAG (RHO(1)=1). CONF is the ~95% white-noise band.
%
%   Missing samples: X may contain NaN at missing timestamps on an otherwise
%   regular grid. Each lag k is estimated from the pairwise-complete set of
%   index pairs (t, t+k) where BOTH samples are observed (a consistent
%   moment estimator). The 4th output NPAIRS gives the pair count per lag;
%   CONF uses the lag-1 pair count. With no NaN this reduces to the standard
%   biased-denominator ACF.  Base MATLAB only.
    x = x(:);
    validateattributes(x, {'numeric'}, {'vector','real'});
    N   = numel(x);
    obs = ~isnan(x);
    if any(~isfinite(x(obs)))
        error('tsAcf:badData','Observed samples must be finite (Inf not allowed).');
    end
    if nargin < 2 || isempty(maxLag), maxLag = min(N-1, 40); end
    maxLag = min(round(maxLag), N-1);

    nObs = sum(obs);
    mu   = sum(x(obs)) / nObs;
    xc   = x - mu;
    xc(~obs) = NaN;                       % keep gaps as NaN for masking

    rho    = ones(maxLag+1, 1);
    nPairs = zeros(maxLag+1, 1);
    nPairs(1) = nObs;
    c0 = sum(xc(obs).^2) / nObs;
    if ~(c0 > 0)
        lags = (0:maxLag)'; conf = 1.96/sqrt(nObs); return;
    end

    hasGaps = nObs < N;
    for k = 1:maxLag
        a = xc(1:N-k); b = xc(k+1:N);
        both = ~isnan(a) & ~isnan(b);
        m = sum(both);
        nPairs(k+1) = m;
        if m == 0
            rho(k+1) = NaN;               % lag unobservable
        elseif hasGaps
            rho(k+1) = (sum(a(both).*b(both)) / m) / c0;   % pairwise (unbiased-count)
        else
            rho(k+1) = (a' * b) / N / c0;                  % biased denom (textbook)
        end
    end
    lags = (0:maxLag)';
    conf = 1.96 / sqrt(max(nPairs(2), 1));
end
