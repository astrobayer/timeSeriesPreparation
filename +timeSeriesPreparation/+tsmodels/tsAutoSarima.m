function [best, tbl] = tsAutoSarima(x, maxOrder, maxSeasonal, s, varargin)
%TSAUTOSARIMA  Grid search over seasonal ARIMA orders minimising an IC.
%
%   [BEST, TBL] = TSAUTOSARIMA(X, [maxp maxd maxq], [maxP maxD maxQ], s)
%   fits every multiplicative seasonal model SARIMA(p,d,q)(P,D,Q)_s over the
%   rectangular grid 0<=p<=maxp, ..., 0<=Q<=maxQ (excluding the all-zero
%   model) with tsFitSarima and returns the model with the smallest
%   information criterion, plus a sorted results table.
%
%   Differencing orders (d, D) are searched as part of the grid; because the
%   likelihoods of models with different amounts of differencing are not
%   directly comparable, the criterion is computed on a common footing by
%   penalising each fit's own (nObs-based) AIC/BIC as returned by
%   tsFitSarima. For a stricter comparison fix d and D (maxd = maxD = 0 with
%   a chosen [_ d _] / [_ D _]) or pre-difference the series.
%
%   Base MATLAB only.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     x            Nx1 double [double]
%       Time series (finite; gaps only with 'Method','exact' and d=D=0).
%     maxOrder     1x3 double [double]
%       Upper non-seasonal orders [maxp maxd maxq] (each >= 0). Default
%       [2 1 2].
%     maxSeasonal  1x3 double [double]
%       Upper seasonal orders [maxP maxD maxQ] (each >= 0). Default [1 1 1].
%     s            1x1 double [double]
%       Seasonal period (>= 2). Required.
%     varargin     name-value [mixed]
%       'Criterion' ('aic'|'bic') selection criterion. Default 'aic'.
%       ... any further options are forwarded to tsFitSarima (e.g.
%       'Method','exact', 'Constant', 'NStart').
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     best   1x1 struct [struct]
%       Best-fitting model (a tsFitSarima struct).
%     tbl    Rx9 double [double]
%       Rows [p d q P D Q criterion aic bic] sorted ascending by criterion,
%       one row per successfully fitted order combination.
%
%   See also: tsFitSarima, tsAutoArima, tsForecast, tsModelDisp.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (tsmodels)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%
%   Example
%     [m, T] = tsAutoSarima(x, [2 1 2], [1 1 1], 12, 'Criterion', 'bic');
%     tsModelDisp(m);

    narginchk(4, inf);
    if nargin < 2 || isempty(maxOrder),    maxOrder    = [2 1 2]; end
    if nargin < 3 || isempty(maxSeasonal), maxSeasonal = [1 1 1]; end
    validateattributes(maxOrder,    {'numeric'}, {'numel',3,'nonnegative','integer'}, mfilename, 'maxOrder');
    validateattributes(maxSeasonal, {'numeric'}, {'numel',3,'nonnegative','integer'}, mfilename, 'maxSeasonal');
    validateattributes(s, {'numeric'}, {'scalar','integer','>=',2}, mfilename, 's');

    crit = 'aic';  keep = {};
    i = 1;
    while i <= numel(varargin)
        if strcmpi(varargin{i}, 'Criterion')
            crit = lower(char(varargin{i+1})); i = i + 2;
        else
            keep(end+1:end+2) = varargin(i:i+1); i = i + 2; %#ok<AGROW>
        end
    end
    if ~any(strcmp(crit, {'aic','bic'}))
        error('tsAutoSarima:criterion', 'Criterion must be ''aic'' or ''bic''.');
    end

    mp = maxOrder(1); md = maxOrder(2); mq = maxOrder(3);
    mP = maxSeasonal(1); mD = maxSeasonal(2); mQ = maxSeasonal(3);

    rows = [];  models = {};
    for p = 0:mp
      for d = 0:md
        for q = 0:mq
          for P = 0:mP
            for D = 0:mD
              for Q = 0:mQ
                if (p+d+q+P+D+Q) == 0, continue; end
                try
                    mdl = timeSeriesPreparation.tsmodels.tsFitSarima(x, [p d q], [P D Q], s, keep{:});
                    switch crit
                        case 'aic', c = mdl.aic;
                        case 'bic', c = mdl.bic;
                    end
                    if ~isfinite(c), continue; end
                    rows(end+1,:) = [p d q P D Q c mdl.aic mdl.bic]; %#ok<AGROW>
                    models{end+1} = mdl;                              %#ok<AGROW>
                catch
                    % skip orders that fail to fit / are too short
                end
              end
            end
          end
        end
      end
    end

    if isempty(rows)
        error('tsAutoSarima:noFit', ...
            'No SARIMA order in the grid could be fitted to the series.');
    end

    [~, ix] = sortrows(rows, 7);
    tbl  = rows(ix, :);
    best = models{ix(1)};
end
