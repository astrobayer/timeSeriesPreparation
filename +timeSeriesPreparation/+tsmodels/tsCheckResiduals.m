function out = tsCheckResiduals(model, lags)
%TSCHECKRESIDUALS  Residual diagnostics for a fitted ARIMA/SARIMA model.
%
%   OUT = TSCHECKRESIDUALS(MODEL) produces the standard four-panel residual
%   diagnostic for a model returned by TSFITARIMA (or a wrapper): the
%   standardized residual series, the residual ACF with white-noise band,
%   a normal Q-Q plot, and a Ljung-Box p-value ladder across lags. It also
%   returns a struct of the underlying numbers so the checks can be scripted
%   without the figure.
%
%   OUT = TSCHECKRESIDUALS(MODEL, LAGS) sets the maximum lag for the ACF and
%   the Ljung-Box ladder (default min(20, floor(nObs/4))).
%
%   Base MATLAB only.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     model   1x1 struct [struct]
%       Fitted model from tsFitArima / tsFitAR / tsFitMA / tsFitARMA /
%       tsAutoArima. Uses model.resid, model.obs, model.p, model.q, model.d
%       (and model.P, model.Q, model.season for SARIMA parameter counting).
%     lags    1x1 double [double]
%       (optional) Maximum lag for the ACF and Ljung-Box ladder. Default
%       min(20, floor(nObs/4)).
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     out     1x1 struct [struct]
%       Diagnostic results with fields:
%         .resid        (Nx1 double) standardized residuals (NaN at gaps).
%         .acf          (Lx1 double) residual autocorrelations, lags 1..L.
%         .acfConf      (1x1 double) +/- white-noise band for the ACF.
%         .lags         (Lx1 double) lag axis 1..L.
%         .lbLags       (Lx1 double) Ljung-Box lag axis.
%         .lbP          (Lx1 double) Ljung-Box p-value at each lag.
%         .lbQ          (Lx1 double) Ljung-Box statistic at each lag.
%         .jbStat       (1x1 double) Jarque-Bera normality statistic.
%         .jbP          (1x1 double) Jarque-Bera p-value (chi2, df=2).
%         .figure       (1x1 handle) the created figure (invalid if none).
%
%   See also: tsFitArima, tsLjungBox, tsAcf, tsModelDisp.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (tsmodels)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------

    narginchk(1, 2);
    e = model.resid(:);
    obs = true(size(e));
    if isfield(model, 'obs') && ~isempty(model.obs), obs = model.obs(:); end

    % Standardize the observed residuals (zero-mean, unit-variance view)
    eObs = e(obs & isfinite(e));
    eObs = eObs(eObs ~= 0 | true);            % keep all finite observed
    mu = mean(eObs); sd = std(eObs);
    if ~(sd > 0), sd = 1; end
    z = (e - mu) / sd;                        % standardized (NaN stays NaN)

    nObs = numel(eObs);
    if nargin < 2 || isempty(lags)
        lags = min(20, max(1, floor(nObs/4)));
    end
    lags = min(round(lags), nObs - 1);

    nParam = local_paramCount(model);

    % ---- residual ACF ---------------------------------------------------
    [rho, ~, acfConf] = timeSeriesPreparation.tsmodels.tsAcf(e, lags);
    acf = rho(2:end);
    lagAxis = (1:lags)';

    % ---- Ljung-Box ladder ----------------------------------------------
    lbQ = zeros(lags,1); lbP = zeros(lags,1);
    for L = 1:lags
        dfL = max(L - nParam, 1);
        [Q, pv] = timeSeriesPreparation.tsmodels.tsLjungBox(e, L, nParam); %#ok<ASGLU>
        lbQ(L) = Q; lbP(L) = pv;
    end

    % ---- Jarque-Bera normality -----------------------------------------
    zc = eObs - mean(eObs); s = std(eObs, 1);
    if ~(s > 0), s = 1; end
    zc = zc / s;
    skew = mean(zc.^3);
    kurt = mean(zc.^4);
    jbStat = nObs/6 * (skew^2 + (kurt - 3)^2/4);
    jbP    = 1 - local_chi2cdf(jbStat, 2);

    out = struct();
    out.resid   = z;
    out.acf     = acf;
    out.acfConf = acfConf;
    out.lags    = lagAxis;
    out.lbLags  = lagAxis;
    out.lbP     = lbP;
    out.lbQ     = lbQ;
    out.jbStat  = jbStat;
    out.jbP     = jbP;
    out.figure  = matlab.graphics.GraphicsPlaceholder;

    % ---- plot -----------------------------------------------------------
    if nargout == 0 || true
        fig = figure('Name', 'tsCheckResiduals', 'Color', 'w');
        out.figure = fig;

        subplot(2,2,1);
        plot(z, 'k-'); hold on; yline(0, ':');
        title('Standardized residuals'); xlabel('t'); ylabel('z'); grid on;

        subplot(2,2,2);
        stem(lagAxis, acf, 'filled', 'MarkerSize', 3); hold on;
        yline([acfConf -acfConf], '--r');
        title('Residual ACF'); xlabel('lag'); ylabel('\rho'); grid on;
        ylim([-1 1]*max(0.2, 1.1*max(abs(acf))));

        subplot(2,2,3);
        zs = sort(zc);
        pp = ((1:nObs)' - 0.5)/nObs;
        theo = local_norminv(pp);
        plot(theo, zs, 'k.', 'MarkerSize', 4); hold on;
        lim = [min(theo(1), zs(1)), max(theo(end), zs(end))];
        plot(lim, lim, 'r-');
        title(sprintf('Normal Q-Q  (JB p=%.3f)', jbP));
        xlabel('theoretical quantile'); ylabel('sample quantile'); grid on;

        subplot(2,2,4);
        stem(lagAxis, lbP, 'filled', 'MarkerSize', 3); hold on;
        yline(0.05, '--r', '5%');
        title('Ljung-Box p-values'); xlabel('lag'); ylabel('p'); grid on;
        ylim([0 1]);
    end
end

% ----------------------------------------------------------------------
function k = local_paramCount(model)
% Number of fitted ARMA parameters (p+q plus seasonal P+Q if SARIMA).
    k = 0;
    if isfield(model,'p'), k = k + model.p; end
    if isfield(model,'q'), k = k + model.q; end
    if isfield(model,'P'), k = k + model.P; end
    if isfield(model,'Q'), k = k + model.Q; end
end

% ----------------------------------------------------------------------
function p = local_chi2cdf(x, k)
    if x <= 0, p = 0; return; end
    p = local_gammainc(x/2, k/2);
end

function g = local_gammainc(x, a)
    if x < a + 1
        ap = a; s = 1/a; del = s;
        for n = 1:1000
            ap = ap + 1; del = del * x/ap; s = s + del;
            if abs(del) < abs(s)*1e-14, break; end
        end
        g = s * exp(-x + a*log(x) - gammaln(a));
    else
        tiny = 1e-300;
        b = x + 1 - a; c = 1/tiny; d = 1/b; h = d;
        for i = 1:1000
            an = -i*(i - a); b = b + 2;
            d = an*d + b; if abs(d) < tiny, d = tiny; end
            c = b + an/c; if abs(c) < tiny, c = tiny; end
            d = 1/d; del = d*c; h = h*del;
            if abs(del - 1) < 1e-14, break; end
        end
        g = 1 - exp(-x + a*log(x) - gammaln(a)) * h;
    end
    g = min(max(g, 0), 1);
end

% ----------------------------------------------------------------------
function z = local_norminv(pp)
% Standard-normal quantile (Acklam rational approximation), vectorised.
    a = [-3.969683028665376e+01  2.209460984245205e+02 -2.759285104469687e+02 ...
          1.383577518672690e+02 -3.066479806614716e+01  2.506628277459239e+00];
    b = [-5.447609879822406e+01  1.615858368580409e+02 -1.556989798598866e+02 ...
          6.680131188771972e+01 -1.328068155288572e+01];
    c = [-7.784894002430293e-03 -3.223964580411365e-01 -2.400758277161838e+00 ...
         -2.549732539343734e+00  4.374664141464968e+00  2.938163982698783e+00];
    dd= [ 7.784695709041462e-03  3.224671290700398e-01  2.445134137142996e+00 ...
          3.754408661907416e+00];
    z = zeros(size(pp));
    plow = 0.02425; phigh = 1 - plow;
    lo = pp < plow; hi = pp > phigh; mid = ~lo & ~hi;
    r = sqrt(-2*log(pp(lo)));
    z(lo) = (((((c(1)*r+c(2)).*r+c(3)).*r+c(4)).*r+c(5)).*r+c(6)) ./ ...
            ((((dd(1)*r+dd(2)).*r+dd(3)).*r+dd(4)).*r+1);
    r = pp(mid) - 0.5; s = r.*r;
    z(mid) = (((((a(1)*s+a(2)).*s+a(3)).*s+a(4)).*s+a(5)).*s+a(6)).*r ./ ...
             (((((b(1)*s+b(2)).*s+b(3)).*s+b(4)).*s+b(5)).*s+1);
    r = sqrt(-2*log(1-pp(hi)));
    z(hi) = -(((((c(1)*r+c(2)).*r+c(3)).*r+c(4)).*r+c(5)).*r+c(6)) ./ ...
             ((((dd(1)*r+dd(2)).*r+dd(3)).*r+dd(4)).*r+1);
end
