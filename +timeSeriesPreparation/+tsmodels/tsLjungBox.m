function [Q, pValue, df] = tsLjungBox(resid, lags, nParam)
%TSLJUNGBOX  Ljung-Box portmanteau test for residual autocorrelation.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     resid   Nx1 double [double]
%       Residual series; NaN entries and leading conditioned zeros are
%       dropped.
%     lags    1x1 double [double]
%       (optional) Number of lags tested. Default 20.
%     nParam  1x1 double [double]
%       (optional) Fitted parameter count p+q, lowers df. Default 0.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     Q       1x1 double [double]
%       Ljung-Box statistic.
%     pValue  1x1 double [double]
%       Upper-tail p-value, 1 - chi2cdf(Q,df).
%     df      1x1 double [double]
%       Degrees of freedom, max(lags-nParam,1).
%
%   See also: tsFitArima, tsAcf, tsModelDisp.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (tsmodels)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%   [Q,PVALUE,DF] = TSLJUNGBOX(RESID,LAGS,NPARAM) tests H0: innovations are
%   uncorrelated up to LAGS lags. NPARAM (=p+q) lowers the chi-square df.
%   Q ~ chi2(LAGS-NPARAM) under H0. Base MATLAB only (own chi2 CDF).
    if nargin < 2 || isempty(lags),   lags = 20;   end
    if nargin < 3 || isempty(nParam), nParam = 0;  end

    e = resid(:);
    e = e(~isnan(e));                         % drop missing-timestamp residuals
    nz = find(e ~= 0, 1, 'first');            % trim leading conditioned zeros
    if ~isempty(nz), e = e(nz:end); end
    e = e - mean(e);
    N = numel(e);
    lags = min(round(lags), N-1);

    r = timeSeriesPreparation.tsmodels.tsAcf(e, lags); r = r(2:end);         % rho_1..rho_lags
    k = (1:lags)';
    Q  = N*(N+2) * sum( r.^2 ./ (N - k) );
    df = max(lags - nParam, 1);
    pValue = 1 - local_chi2cdf(Q, df);
end

% ----------------------------------------------------------------------
function p = local_chi2cdf(x, k)
    if x <= 0, p = 0; return; end
    p = local_gammainc(x/2, k/2);             % regularised lower incomplete gamma
end

function g = local_gammainc(x, a)
    if x < a + 1                              % series expansion
        ap = a; s = 1/a; del = s;
        for n = 1:1000
            ap = ap + 1; del = del * x/ap; s = s + del;
            if abs(del) < abs(s)*1e-14, break; end
        end
        g = s * exp(-x + a*log(x) - gammaln(a));
    else                                      % continued fraction (Lentz)
        tiny = 1e-300;
        b = x + 1 - a; c = 1/tiny; d = 1/b; h = d;
        for i = 1:1000
            an = -i*(i - a); b = b + 2;
            d = an*d + b; if abs(d) < tiny, d = tiny; end
            c = b + an/c; if abs(c) < tiny, c = tiny; end
            d = 1/d; del = d*c; h = h*del;
            if abs(del - 1) < 1e-14, break; end
        end
        g = 1 - exp(-x + a*log(x) - gammaln(a)) * h;
    end
    g = min(max(g, 0), 1);
end
