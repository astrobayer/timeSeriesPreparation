function [y, x0] = tsDiff(x, d)
%TSDIFF  Apply d-th order lag-1 differencing:  Y = (1-B)^D X.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     x       Nx1 double [numeric,real,finite]
%       Input series.
%     d       1x1 double [double]
%       (optional) Differencing order >= 0. Default 0.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     y       (N-d)x1 double [double]
%       Differenced series (1-B)^d x.
%     x0      dx1 double [double]
%       Initial values per differencing level, for tsIntegrate.
%
%   See also: tsIntegrate, tsFitArima.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (tsmodels)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%   [Y,X0] = TSDIFF(X,D) also returns the D initial values X0 needed by
%   TSINTEGRATE to reconstruct X (X0(i) = first value at level i).
%   Base MATLAB only.
    x = x(:);
    % Allow NaN gaps only when d==0 (pass-through); differencing across
    % missing samples is undefined, so require finiteness once d>0.
    validateattributes(x, {'numeric'}, {'vector','real'});
    if nargin < 2 || isempty(d), d = 0; end
    d = round(d);
    if d < 0, error('tsDiff:negativeOrder','D must be >= 0.'); end
    if d > 0 && any(~isfinite(x))
        error('tsDiff:nonfiniteWithDiff', ...
            'Differencing (d>0) requires a finite series (no NaN/Inf gaps).');
    end
    if d >= numel(x), error('tsDiff:tooShort','D too large for series length.'); end
    y = x; x0 = zeros(d,1);
    for i = 1:d
        x0(i) = y(1);
        y = diff(y);
    end
end
