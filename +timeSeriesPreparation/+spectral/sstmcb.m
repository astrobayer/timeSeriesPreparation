function [b, a] = sstmcb(h, nb, na, maxIter)
%SSTMCB  Steiglitz-McBride IIR fit to an impulse response (base MATLAB).
%
%   [B, A] = SSTMCB(H, NB, NA) fits a rational filter B(z)/A(z) of numerator
%   order NB and denominator order NA so that
%       filter(B, A, delta)  approximates  H,
%   i.e. B(z)/A(z) matches the system whose impulse response is H. Uses the
%   Steiglitz-McBride (SM) iteration: at each pass the unit-impulse input and
%   the target H are prefiltered by 1/A_prev, then B and A are re-estimated
%   by linear least squares. This is the equation-error-to-output-error
%   refinement that gives SM its accuracy on rational systems.
%
%   This is a base-MATLAB replacement for the Signal Processing Toolbox STMCB
%   (with a unit-impulse input and internal initial denominator). It uses
%   only FILTER and the backslash operator.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     h        Lx1 double [double]
%       Target impulse response samples (real).
%     nb       1x1 double [double,nonneg,integer]
%       Numerator (zero) order; B has nb+1 coefficients.
%     na       1x1 double [double,nonneg,integer]
%       Denominator (pole) order; A has na+1 coefficients, a(1)=1.
%     maxIter  1x1 double [double,pos,integer]
%       (optional) Number of SM refinement iterations. Default 10.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     b    1x(nb+1) double [double]
%       Numerator polynomial coefficients [b0 ... b_nb].
%     a    1x(na+1) double [double]
%       Denominator polynomial coefficients [1 a1 ... a_na].
%
%   See also: sfreqz, sinvfreqz, psd2arma.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (spectral)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%
%   Example
%     htrue = filter([1 -0.5 0.2], [1 -1.2 0.6], [1; zeros(60,1)]);
%     [b, a] = sstmcb(htrue, 2, 2);      % recovers the generating filter

    narginchk(3, 4);
    if nargin < 4 || isempty(maxIter), maxIter = 10; end
    validateattributes(nb, {'numeric'}, {'scalar','integer','nonnegative'}, mfilename, 'nb');
    validateattributes(na, {'numeric'}, {'scalar','integer','nonnegative'}, mfilename, 'na');
    h = h(:);  N = numel(h);
    x = zeros(N,1);  x(1) = 1;              % unit impulse input
    a = [1; zeros(na,1)];
    b = [];
    for it = 1:maxIter
        xf = filter(1, a, x);              % prefiltered input
        yf = filter(1, a, h);             % prefiltered target
        % Regressor columns: xf shifted 0..nb (for b), -yf shifted 1..na (for a)
        M = zeros(N, nb+1+na);
        for j = 0:nb
            M(j+1:N, j+1) = xf(1:N-j);
        end
        for i = 1:na
            M(i+1:N, nb+1+i) = -yf(1:N-i);
        end
        sol = M \ yf;
        b = sol(1:nb+1);
        a = [1; sol(nb+2:end)];
    end
    b = b(:).';  a = a(:).';
end
