function [b, a] = sinvfreqz(Hd, w, nb, na, maxIter)
%SINVFREQZ  Fit an IIR filter to a complex frequency response (base MATLAB).
%
%   [B, A] = SINVFREQZ(HD, W, NB, NA) fits a rational transfer function
%       B(z)/A(z) ~ HD(w),    z = e^{-jw},   a(1) = 1
%   of numerator order NB and denominator order NA to the target complex
%   response HD sampled at angular frequencies W (rad/sample), by the
%   Sanathanan-Koerner (SK) iteration.
%
%   METHOD
%     Each iteration solves the linearised, denominator-weighted least
%     squares problem  min sum_k |W_k (A(z_k) HD_k - B(z_k))|^2  with the
%     weights W_k = 1/|A_prev(z_k)| updated from the previous denominator.
%     The first iteration is the Levi (equation-error) solution; at
%     convergence this approaches the output-error (true magnitude/phase)
%     fit. Solved in the real domain by stacking real and imaginary parts.
%
%   This is a base-MATLAB replacement for the Signal Processing Toolbox
%   INVFREQZ (default, unweighted, no explicit user weight vector). It
%   recovers a rational HD to machine precision and fits smooth non-rational
%   targets to a fraction of a dB.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     Hd       Mx1 double [complex]
%       Target complex frequency response, one value per frequency in W.
%     w        Mx1 double [double]
%       Angular frequencies [rad/sample], typically in [0, pi].
%     nb       1x1 double [double,nonneg,integer]
%       Numerator (zero) order; B has nb+1 coefficients.
%     na       1x1 double [double,nonneg,integer]
%       Denominator (pole) order; A has na+1 coefficients, a(1)=1.
%     maxIter  1x1 double [double,pos,integer]
%       (optional) Maximum SK reweighting iterations. Default 30.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     b    1x(nb+1) double [double]
%       Numerator polynomial coefficients [b0 ... b_nb].
%     a    1x(na+1) double [double]
%       Denominator polynomial coefficients [1 a1 ... a_na].
%
%   See also: sfreqz, sstmcb, psd2arma, arma2psd.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (spectral)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%
%   Example
%     w  = linspace(0, pi, 400)';
%     Hd = sfreqz([1 -0.5 0.2], [1 -1.2 0.6], w);   % target from known ARMA
%     [b, a] = sinvfreqz(Hd, w, 2, 2);              % recovers it

    narginchk(4, 5);
    if nargin < 5 || isempty(maxIter), maxIter = 30; end
    validateattributes(nb, {'numeric'}, {'scalar','integer','nonnegative'}, mfilename, 'nb');
    validateattributes(na, {'numeric'}, {'scalar','integer','nonnegative'}, mfilename, 'na');
    w  = w(:);  Hd = Hd(:);
    m  = numel(w);  z = exp(-1i*w);

    Zb = zeros(m, nb+1);                    % columns z^0 .. z^nb  (for B)
    zp = ones(m,1);
    for k = 0:nb, Zb(:,k+1) = zp; zp = zp .* z; end
    Za = zeros(m, na);                      % columns z^1 .. z^na  (for A, a0=1)
    zp = z;
    for k = 1:na, Za(:,k) = zp; zp = zp .* z; end

    Wk = ones(m,1);
    a  = [1; zeros(na,1)];
    b  = zeros(nb+1,1);
    for it = 1:maxIter
        % rows:  Wk*( Zb*b - (Za.*Hd)*a(2:end) ) = Wk*Hd
        M   = [Zb, -(Za .* Hd)];            % m x (nb+1+na)
        Wc  = Wk;
        Als = [real(Wc).*real(M) - imag(Wc).*imag(M); ...
               real(Wc).*imag(M) + imag(Wc).*real(M)];
        rhs = Wk .* Hd;
        bls = [real(rhs); imag(rhs)];
        x   = Als \ bls;                    % base-MATLAB least squares
        b   = x(1:nb+1);
        a   = [1; x(nb+2:end)];
        Az  = 1 + Za*a(2:end);
        newWk = 1 ./ max(abs(Az), 1e-12);
        if norm(newWk - Wk) <= 1e-9*max(norm(Wk), 1e-12)
            Wk = newWk; break;
        end
        Wk = newWk;
    end
    b = b(:).';  a = a(:).';
end
