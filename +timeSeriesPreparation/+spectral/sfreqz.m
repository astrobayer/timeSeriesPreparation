function [H, w] = sfreqz(b, a, w, Fs)
%SFREQZ  Digital frequency response of an IIR/FIR filter (base MATLAB).
%
%   H = SFREQZ(B, A, W) returns the complex frequency response
%       H(e^{jw}) = B(z)/A(z)   evaluated at z = e^{-jw}
%   of the rational filter with numerator B(z) = b(1) + b(2) z^-1 + ... and
%   denominator A(z) = a(1) + a(2) z^-1 + ..., at the angular frequencies W
%   (radians/sample, typically in [0, pi]).
%
%   H = SFREQZ(B, A, F, FS) treats the third argument as physical
%   frequencies F in Hz and converts internally with w = 2*pi*F/Fs.
%
%   [H, W] = SFREQZ(...) also returns the angular-frequency vector used.
%
%   This is a base-MATLAB replacement for the Signal Processing Toolbox
%   FREQZ, sufficient for evaluating a response on a supplied grid (it does
%   not auto-generate a grid or plot). Works with real or complex b, a and
%   preserves the numeric class of W (single/gpuArray).
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     b    1x(nb+1) double [double]
%       Numerator polynomial coefficients [b0 b1 ... b_nb] (ascending z^-1).
%     a    1x(na+1) double [double]
%       Denominator polynomial coefficients [a0 a1 ... a_na]; a0 is usually 1.
%     w    Mx1 double [double]
%       Angular frequencies [rad/sample] (or physical Hz if Fs is given).
%     Fs   1x1 double [double,pos]
%       (optional) Sample rate [Hz]. If present, w is interpreted as Hz and
%       converted to rad/sample via 2*pi*w/Fs.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     H    Mx1 double [complex]
%       Complex frequency response at each requested frequency.
%     w    Mx1 double [double]
%       Angular-frequency vector actually used [rad/sample].
%
%   See also: sinvfreqz, sstmcb, arma2psd, psd2arma.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (spectral)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%
%   Example
%     w = linspace(0, pi, 512)';
%     H = sfreqz([1 -0.5 0.2], [1 -1.2 0.6], w);
%     plot(w, 20*log10(abs(H)));

    narginchk(3, 4);
    w = w(:);
    if nargin >= 4 && ~isempty(Fs)
        validateattributes(Fs, {'numeric'}, {'scalar','positive','finite'}, mfilename, 'Fs');
        w = 2*pi*w/Fs;
    end
    b = b(:).';  a = a(:).';
    z  = exp(-1i*w);                       % z^{-1} sample points
    B  = polyvalAsc(b, z);
    A  = polyvalAsc(a, z);
    A(abs(A) < 1e-300) = 1e-300;
    H  = B ./ A;
end

% ----------------------------------------------------------------------
function y = polyvalAsc(c, z)
% Evaluate c(1) + c(2)*z + ... + c(n+1)*z^n (ascending powers of z).
y  = zeros(size(z), 'like', z);
zp = ones(size(z), 'like', z);
for k = 1:numel(c)
    y  = y + c(k)*zp;
    zp = zp .* z;
end
end
