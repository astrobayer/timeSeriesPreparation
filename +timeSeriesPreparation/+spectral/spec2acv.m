function [R, lags, info] = spec2acv(f, S, opts)
%SPEC2ACV  Convert a one- or two-sided PSD/ASD to auto-covariance / -correlation.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     f       Mx1 double [numeric,real]
%       Frequency grid [Hz]. May be non-uniform/log-spaced/unsorted;
%       negative entries only with Sided="two". M >= 3 points.
%     S       Mx1 double [numeric]
%       Spectral density on f. PSD (unit^2/Hz) by default, or ASD
%       (unit/sqrt(Hz)) with InputType="asd".
%     opts    1x1 struct [name-value]
%       Options: InputType, Sided, Output("acv"|"acf"),
%       Method("ifft"|"direct"), Lags, InterpFactor, MaxBins,
%       ResampleSpace, Window, WindowParam, Smooth, SmoothWidth, DOF,
%       NanPolicy, GridTol. See in-file help.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     R       Lx1 double [double]
%       Auto-covariance (or auto-correlation if Output="acf") at lags.
%       Same numeric class as input. L lag points.
%     lags    Lx1 double [double]
%       Lag axis [s], starting at 0 for the default grid.
%     info    1x1 struct [struct]
%       Diagnostics: df, dt, N, resampled, resampleSpace, nBadBins,
%       varIn, varOut, windowLoss, integralTimescale, firstZero,
%       tauDecorr, Rstd ([] unless DOF given).
%
%   See also: psd2arma, plotPowerSpectrum, spec2acvTest.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (spectral)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%
%   [R, lags] = SPEC2ACV(f, S) transforms the spectral density S on the
%   frequency grid f into the auto-covariance R(lags) via the
%   Wiener-Khinchin theorem. Non-uniform, offset, unsorted, or log-spaced
%   grids are resampled onto a uniform grid automatically. R and lags are
%   column vectors; single and gpuArray inputs are preserved.
%
%   [R, lags, info] = SPEC2ACV(...) returns diagnostics and derived
%   quantities (see below).
%
%   Name-value options
%   ------------------
%   InputType     "psd" (default) | "asd"
%                 "asd": S is squared internally before any processing.
%   Sided         "one" (default) | "two"
%                 "two": f may contain negative frequencies; the spectrum
%                 is folded, G(f) = S2(f) + S2(-f), before processing.
%   Output        "acv" (default) | "acf"  (acf = R(tau)/R(0))
%   Method        "ifft" (default) | "direct"
%                 "ifft"  : fast, lag grid fixed to dt = 1/(2*fNyq).
%                 "direct": trapezoidal quadrature at arbitrary lags
%                 (see 'Lags'); uses NUFFT when available (R2020a+),
%                 otherwise an O(N*L) cosine matrix.
%   Lags          Lag vector in seconds ("direct" only).
%                 Default: same grid as "ifft".
%   InterpFactor  Integer >= 1 (default 1). Refines df -> df/K by
%                 shape-preserving interpolation; extends the maximum lag
%                 T = 1/(2*df) by the factor K.
%   MaxBins       Cap on the uniform grid size (default 2^20). If the
%                 requested resolution exceeds it, df is coarsened with a
%                 warning. Protects against log grids reaching into mHz.
%   ResampleSpace "auto" (default) | "linear" | "loglog"
%                 Interpolation space for resampling. "loglog"
%                 interpolates log S vs log f (correct for power laws);
%                 "auto" picks "loglog" for log-spaced, positive spectra.
%   Window        "none" (default) | "cosine"/"hann" | "hamming" |
%                 "blackman" | "gauss" | "tukey" | "exp"
%                 Spectral taper w(f), w(0) = 1, roll-off to Nyquist.
%   WindowParam   gauss : alpha (sigma = fNyq/alpha), default 2.5
%                 tukey : taper ratio in [0,1],       default 0.5
%                 exp   : decay k, w = exp(-k*f/fNyq), default 3
%   Smooth        "none" (default) | "boxcar" | "triangle" |
%                 "cosine"/"hann" | "gauss" | "octave"
%                 Kernel modes convolve with a fixed-width kernel;
%                 "octave" applies constant-relative-bandwidth (boxcar)
%                 smoothing in log frequency - use this for wideband ASDs.
%   SmoothWidth   Kernel modes: full width in Hz ("gauss": +/-3 sigma),
%                 default 10*df. "octave" mode: bandwidth in octaves,
%                 default 1/3 (i.e. third-octave smoothing).
%   DOF           Equivalent degrees of freedom of the PSD estimate
%                 (chi-squared model, e.g. ~2*nAvg for Welch). If given,
%                 the 1-sigma uncertainty of R is propagated to
%                 info.Rstd, accounting for the variance reduction of the
%                 chosen smoothing. Default NaN (off).
%   NanPolicy     "interp" (default) | "zero" | "error"
%   GridTol       Relative tolerance for accepting a grid as uniform and
%                 DC-aligned without resampling. Default 1e-6.
%
%   info fields
%   -----------
%   df, dt, N, resampled, resampleSpace, nBadBins
%   varIn              trapz of the input PSD (process variance)
%   varOut             R(0) after smoothing/taper (same quadrature)
%   windowLoss         1 - varOut/varIn
%   integralTimescale  trapz(lags, R)/R(0)              [s]
%   firstZero          first zero crossing of the ACF   [s] (NaN if none)
%   tauDecorr          first crossing of ACF = 1/e      [s] (NaN if none)
%   Rstd               1-sigma uncertainty of R (only if DOF given; for
%                      Output="acf" it is normalized by R(0), neglecting
%                      the R(0) uncertainty)
%
%   Notes
%   -----
%   * Below the lowest measured frequency the spectrum is zero-padded;
%     above the highest it is assumed zero.
%   * With Window="none" and Smooth="none": R(0) == trapz(f,S) exactly.
%     Both methods use trapezoidal quadrature; DC and Nyquist bins carry
%     half weight, so "ifft" and "direct" agree to rounding error.
%   * A warning is issued if S has not decayed at Nyquist and no taper
%     is applied (ringing).
%   * Run SPEC2ACVTEST for the analytic validation suite.
%
%   Example
%   -------
%     fs = 1000; f = (0:0.5:fs/2)';
%     S  = 1./(1 + (f/50).^4);
%     [R, tau, nfo] = spec2acv(f, S, Window="tukey", Smooth="octave", ...
%                              SmoothWidth=1/6, DOF=32, Output="acf");
%     errorbar(tau(1:5:200), R(1:5:200), 1.96*nfo.Rstd(1:5:200)); grid on
%
%   See also SPEC2ACVTEST, IFFT, NUFFT, XCORR.

arguments
    f (:,1) {mustBeNumeric, mustBeReal}
    S (:,1) {mustBeNumeric}
    opts.InputType     (1,1) string {mustBeMember(opts.InputType, ["psd","asd"])} = "psd"
    opts.Sided         (1,1) string {mustBeMember(opts.Sided, ["one","two"])} = "one"
    opts.Output        (1,1) string {mustBeMember(opts.Output, ["acv","acf"])} = "acv"
    opts.Method        (1,1) string {mustBeMember(opts.Method, ["ifft","direct"])} = "ifft"
    opts.Lags          (:,1) {mustBeNumeric, mustBeReal, mustBeNonnegative} = []
    opts.InterpFactor  (1,1) {mustBeInteger, mustBePositive} = 1
    opts.MaxBins       (1,1) {mustBeInteger, mustBePositive} = 2^20
    opts.ResampleSpace (1,1) string {mustBeMember(opts.ResampleSpace, ["auto","linear","loglog"])} = "auto"
    opts.Window        (1,1) string {mustBeMember(opts.Window, ...
                       ["none","cosine","hann","hamming","blackman","gauss","tukey","exp"])} = "none"
    opts.WindowParam   (1,1) {mustBeNumeric, mustBeReal} = NaN
    opts.Smooth        (1,1) string {mustBeMember(opts.Smooth, ...
                       ["none","boxcar","triangle","cosine","hann","gauss","octave"])} = "none"
    opts.SmoothWidth   (1,1) {mustBeNumeric, mustBeReal, mustBePositive} = Inf
    opts.DOF           (1,1) {mustBeNumeric, mustBeReal} = NaN
    opts.NanPolicy     (1,1) string {mustBeMember(opts.NanPolicy, ["interp","zero","error"])} = "interp"
    opts.GridTol       (1,1) {mustBeNumeric, mustBeReal, mustBePositive} = 1e-6
end

%% ---- Basic validation --------------------------------------------------
if numel(f) ~= numel(S)
    error("spec2acv:sizeMismatch", "f and S must have the same length.");
end
if numel(f) < 3
    error("spec2acv:tooShort", "Need at least 3 spectral points.");
end
if ~isempty(opts.Lags) && opts.Method ~= "direct"
    error("spec2acv:lagsNeedDirect", "'Lags' requires Method=""direct"".");
end
if opts.Sided == "one" && any(f < 0)
    error("spec2acv:negFreq", ...
        "Negative frequencies found; use Sided=""two"" for two-sided spectra.");
end
if ~isnan(opts.DOF) && ~(opts.DOF > 0)
    error("spec2acv:badDOF", "DOF must be positive.");
end
if ~isreal(S)
    if max(abs(imag(S))) > 1e-9*max(abs(S))
        warning("spec2acv:complexS", ...
            "S is complex; using abs(S). A PSD/ASD should be real.");
    end
    S = abs(S);
end
if isinteger(S), S = double(S); end        % single / gpuArray pass through
if isinteger(f), f = double(f); end

%% ---- Sort, deduplicate -------------------------------------------------
[f, iSrt] = sort(f);
S = S(iSrt);
if any(diff(f) == 0)
    [f, ~, ic] = unique(f);
    S = accumarray(ic, S, [], @mean);
end

%% ---- Fold two-sided spectra --------------------------------------------
if opts.Sided == "two"
    ip = f >= 0;
    fp = f(ip);  Sp = S(ip);
    fn = -flipud(f(~ip));  Sn = flipud(S(~ip));   % ascending |f| of neg branch
    if isempty(fp) || fp(1) > 0                    % ensure a DC bin exists
        fp = [0; fp];  Sp = [zeros(1, "like", S); Sp];
    end
    add = zeros(size(fp), "like", S);
    if ~isempty(fn)
        pos = fp > 0;
        add(pos) = interp1(fn, Sn, fp(pos), "linear", 0);
    end
    add(fp == 0) = Sp(fp == 0);            % S2(-0) = S2(+0): fold doubles DC
    f = fp;  S = Sp + add;
end

%% ---- Repair bad bins (NaN/Inf/negative) --------------------------------
bad = ~isfinite(S);
info.nBadBins = nnz(bad);
if any(bad)
    switch opts.NanPolicy
        case "error"
            error("spec2acv:badBins", "%d non-finite bins in S.", nnz(bad));
        case "zero"
            S(bad) = 0;
        case "interp"
            if nnz(~bad) < 2
                error("spec2acv:badBins", "Too few valid bins to interpolate.");
            end
            S(bad) = interp1(f(~bad), S(~bad), f(bad), "pchip", 0);
    end
end
if any(S < 0)
    tol = 1e-9 * max(S);
    if any(S < -tol)
        warning("spec2acv:negS", ...
            "%d negative bins in S clipped to zero.", nnz(S < -tol));
    end
    S = max(S, 0);
end

%% ---- ASD -> PSD (so all interpolation happens in power) ----------------
if opts.InputType == "asd"
    S = S.^2;
end

%% ---- Resample onto a uniform, DC-aligned grid --------------------------
d      = diff(f);
dfHat  = median(d);
isUnif = all(abs(d - dfHat) <= opts.GridTol * dfHat);
isAlgn = abs(f(1) - round(f(1)/dfHat)*dfHat) <= opts.GridTol * dfHat;
info.resampleSpace = "none";

if isUnif && isAlgn && opts.InterpFactor == 1 && numel(f) + round(f(1)/dfHat) <= opts.MaxBins
    df = dfHat;
    if f(1) > df/2
        nPad = round(f(1)/df);
        S = [zeros(nPad, 1, "like", S); S];
        f = [(0:nPad-1)'*df; f];
    end
    info.resampled = false;
else
    df = min(d(d > 0)) / opts.InterpFactor;
    if ceil(f(end)/df) + 1 > opts.MaxBins
        df = f(end) / (opts.MaxBins - 1);
        warning("spec2acv:maxBins", ...
            "Requested grid exceeds MaxBins = %d; df coarsened to %.3g Hz.", ...
            opts.MaxBins, df);
    end
    % choose interpolation space
    space = opts.ResampleSpace;
    fpos  = f(f > 0);
    if space == "auto"
        rlog = diff(log(fpos));
        logSpaced = numel(fpos) > 4 && std(rlog)/mean(rlog) < 0.2;
        mostlyPos = mean(S > 0) > 0.9;
        space = "linear"; if logSpaced && mostlyPos, space = "loglog"; end
    end
    fu = (0:ceil(f(end)/df))' * df;
    Su = zeros(numel(fu), 1, "like", S);
    in = fu >= f(1) & fu <= f(end);
    if space == "loglog"
        ok = f > 0 & S > 0;
        if nnz(ok) < 4
            space = "linear";
        else
            inp = in & fu > 0;
            Su(inp) = exp(interp1(log(f(ok)), log(S(ok)), log(fu(inp)), "pchip"));
            if in(1) && fu(1) == 0 && f(1) == 0, Su(1) = S(1); end
        end
    end
    if space == "linear"
        Su(in) = max(interp1(f, S, fu(in), "pchip"), 0);
    end
    f = fu;  S = Su;
    info.resampled = true;
    info.resampleSpace = space;
end
N = numel(S);
info.df = df;  info.N = N;
info.varIn = trapz(f, S);

%% ---- Smooth the spectrum ------------------------------------------------
dofGain = ones(N, 1, "like", S);           % variance-reduction factor per bin
switch opts.Smooth
    case "none"
        % nothing
    case "octave"
        w = opts.SmoothWidth; if isinf(w), w = 1/3; end
        [S, dofGain] = smoothOctave(S, w, N);
    otherwise
        [S, g] = smoothKernel(S, opts.Smooth, opts.SmoothWidth, df);
        dofGain(:) = g;
end

%% ---- Spectral taper -----------------------------------------------------
if opts.Window ~= "none"
    S = S .* taper(f/f(end), opts.Window, opts.WindowParam);
elseif S(end) > 0.01 * max(S)
    warning("spec2acv:notDecayed", ...
        ['Spectrum has not decayed at Nyquist (S(fNyq) = %.1f%% of max); ' ...
         'expect ringing in the ACV. Consider a taper, e.g. Window="tukey".'], ...
        100*S(end)/max(S));
end

%% ---- Transform ----------------------------------------------------------
wTrap = ones(N, 1, "like", S);  wTrap([1 N]) = 0.5;
useNufft = ~isempty(which("nufft"));

switch opts.Method
    case "ifft"
        % Trapezoidal half-weight at DC and Nyquist: identical quadrature
        % to Method="direct", and R(0) == trapz(f,S) exactly.
        S2 = [S(1); S(2:N-1); S(N); flipud(S(2:N-1))] / 2;
        M  = numel(S2);                     % = 2*(N-1)
        R  = M * df * ifft(S2, "symmetric");
        R  = R(1:N);
        lags = (0:N-1)' / (M*df);
    case "direct"
        if isempty(opts.Lags)
            M    = 2*(N-1);
            lags = (0:N-1)' / (M*df);
        else
            lags = opts.Lags;
        end
        R = cosTransform(wTrap .* S, f, lags, df, useNufft);
end

if numel(lags) > 1, info.dt = median(diff(lags)); else, info.dt = NaN; end
info.varOut     = df * (wTrap' * S);
info.windowLoss = 1 - info.varOut / max(info.varIn, realmin);

%% ---- Derived time scales (require lag grid starting at 0) ---------------
info.integralTimescale = NaN; info.firstZero = NaN; info.tauDecorr = NaN;
if numel(lags) > 2 && lags(1) == 0 && all(diff(lags) > 0) && info.varOut > 0
    rho = R / info.varOut;
    info.integralTimescale = trapz(lags, R) / info.varOut;
    info.firstZero = firstCrossing(lags, rho, 0);
    info.tauDecorr = firstCrossing(lags, rho, exp(-1));
end

%% ---- Uncertainty propagation (chi-squared PSD model) ---------------------
info.Rstd = [];
if ~isnan(opts.DOF)
    sig2 = 2 * S.^2 ./ (opts.DOF * dofGain);        % var of smoothed+tapered S
    a    = (wTrap.^2) .* sig2;
    % var R(tau) = df^2 * sum a*cos^2 = df^2*(sum(a) + C2(tau))/2,
    % with C2 = sum a*cos(2*pi*(2f)*tau)
    C2 = cosTransform(a, 2*f, lags, 1, useNufft);   % df=1: raw sum
    if ~isempty(C2)
        info.Rstd = df * sqrt(max((sum(a) + C2)/2, 0));
    else
        warning("spec2acv:ciSkipped", ...
            "Rstd skipped: transform too large and no NUFFT available.");
    end
end

%% ---- Normalize if autocorrelation requested ------------------------------
if opts.Output == "acf"
    R0 = info.varOut;
    if ~(R0 > 0)
        error("spec2acv:zeroVariance", "R(0) <= 0; cannot normalize.");
    end
    R = R / R0;
    if ~isempty(info.Rstd), info.Rstd = info.Rstd / R0; end
end
end

% ==========================================================================
function R = cosTransform(x, f, lags, df, useNufft)
% R(tau_l) = df * sum_j x_j * cos(2*pi*f_j*tau_l), via NUFFT or matrix.
% Returns [] if the matrix would be too large and NUFFT is unavailable.
if useNufft
    try
        R = df * real(nufft(x, f, lags));
        return
    catch
        % fall through to matrix path (e.g. unsupported type)
    end
end
if numel(x) * numel(lags) > 5e7
    R = [];
    return
end
R = df * (cos(2*pi*lags*f') * x);
end

% ==========================================================================
function tau0 = firstCrossing(lags, rho, level)
% First downward crossing of rho through 'level', linearly interpolated.
idx = find(rho(2:end) <= level & rho(1:end-1) > level, 1) + 1;
if isempty(idx)
    tau0 = NaN;
else
    r1 = rho(idx-1); r2 = rho(idx);
    tau0 = lags(idx-1) + (r1 - level)/(r1 - r2) * (lags(idx) - lags(idx-1));
    tau0 = double(gather(tau0));
end
end

% ==========================================================================
function w = taper(x, name, p)
% x in [0,1] = f/fNyq. All tapers: w(0) = 1, roll-off towards Nyquist.
switch name
    case {"cosine","hann"}
        w = 0.5*(1 + cos(pi*x));
    case "hamming"
        w = 0.54 + 0.46*cos(pi*x);
    case "blackman"
        w = 0.42 + 0.5*cos(pi*x) + 0.08*cos(2*pi*x);
    case "gauss"
        if isnan(p), p = 2.5; end
        validateattributes(p, "numeric", "positive", "", "WindowParam");
        w = exp(-0.5*(p*x).^2);
    case "tukey"
        if isnan(p), p = 0.5; end
        if p < 0 || p > 1
            warning("spec2acv:tukeyClamp", "Tukey ratio clamped to [0,1].");
            p = min(max(p, 0), 1);
        end
        w = ones(size(x));
        if p > 0
            idx = x > 1 - p;
            w(idx) = 0.5*(1 + cos(pi*(x(idx) - (1-p))/p));
        end
    case "exp"
        if isnan(p), p = 3; end
        validateattributes(p, "numeric", "positive", "", "WindowParam");
        w = exp(-p*x);
end
end

% ==========================================================================
function [S, g] = smoothKernel(S, name, widthHz, df)
% Fixed-width kernel convolution; edge renormalization preserves power.
% g = variance-reduction factor of the kernel (per-bin DOF multiplier).
if isinf(widthHz), widthHz = 10*df; end
n = max(1, round(widthHz/df/2));
x = (-n:n)'/max(n, 1);
switch name
    case "boxcar",           k = ones(size(x));
    case "triangle",         k = 1 - abs(x);
    case {"cosine","hann"},  k = 0.5*(1 + cos(pi*x));
    case "gauss",            k = exp(-0.5*(3*x).^2);
end
k = k / sum(k);
g = 1 / sum(k.^2);
S = conv(S, k, "same") ./ conv(ones(size(S), "like", S), k, "same");
end

% ==========================================================================
function [S, g] = smoothOctave(S, wOct, N)
% Constant-relative-bandwidth (boxcar) smoothing: each bin i > 1 is the
% mean over f in [f_i*2^(-w/2), f_i*2^(w/2)]. O(N) via cumulative sums.
% The DC bin is left untouched. g = window length in bins.
g  = ones(N, 1, "like", S);
cs = [zeros(1, "like", S); cumsum(S)];
i  = (2:N)';                                % bin index, f_i = (i-1)*df
lo = max(2, ceil((i-1)*2^(-wOct/2)*(1 - 1e-12)) + 1);
hi = min(N, floor((i-1)*2^( wOct/2)*(1 + 1e-12)) + 1);
hi = max(hi, lo);
n  = hi - lo + 1;
S(i) = (cs(hi+1) - cs(lo)) ./ n;
g(i) = n;
end
