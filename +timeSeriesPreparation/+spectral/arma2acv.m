function [R, lags, info] = arma2acv(b, a, maxLag, varargin)
%ARMA2ACV  Exact auto-covariance / -correlation of a discrete-time ARMA process.
%
%   [R, lags] = ARMA2ACV(B, A, MAXLAG) returns the theoretical auto-
%   covariance sequence R(0..MAXLAG) of the stationary ARMA process
%       x[n] = filter(B, A, w[n]),   w[n] ~ white, variance sigma_w^2,
%   evaluated at integer lags lags = (0:MAXLAG)' (in samples). The default
%   method is an exact state-space solve of the discrete Lyapunov equation,
%   so R carries no truncation error and R(1) is the exact process variance.
%
%   This closes the spectral <-> time-series loop together with ARMA2PSD and
%   SPEC2ACV: the same ARMA model yields (a) its PSD via ARMA2PSD, (b) the
%   auto-covariance of that PSD via SPEC2ACV, and (c) the auto-covariance
%   directly via ARMA2ACV; (b) and (c) agree to quadrature accuracy.
%
%   Base MATLAB only.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     b        1x(nb+1) double [double]
%       MA / numerator polynomial B(z) = b(1) + b(2) z^-1 + ...  (b(1) is
%       the leading coefficient; a pure-AR process has b = 1).
%     a        1x(na+1) double [double]
%       AR / denominator polynomial A(z), a(1) normally 1. The process must
%       be stationary (all roots of A inside the unit circle); this is
%       checked and errored on.
%     maxLag   1x1 double [double,nonneg,integer]
%       Largest lag (in samples) to return. R and lags have maxLag+1
%       elements, for lags 0,1,...,maxLag.
%     varargin name-value [mixed]
%       'NoiseVariance' (1x1 double) sigma_w^2 of the driving noise.
%                       Default 1. R scales linearly with this.
%       'Output'        ("acv"|"acf") auto-covariance (default) or auto-
%                       correlation R(k)/R(0).
%       'Method'        ("lyapunov"|"psi") exact state-space solve (default)
%                       or MA(inf) psi-weight convolution (approximate;
%                       controlled by 'PsiTerms').
%       'PsiTerms'      (1x1 double) number of psi-weights for Method="psi".
%                       Default: chosen from the slowest pole so the tail is
%                       below ~1e-12 of R(0), capped at 1e5.
%       'Fs'            (1x1 double) sample rate [Hz]. If given, lags are
%                       returned in SECONDS (lags = (0:maxLag)'/Fs) and
%                       info.dt = 1/Fs; otherwise lags are in samples.
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     R        (maxLag+1)x1 double [double]
%       Auto-covariance (or auto-correlation) at lags 0..maxLag. Column.
%     lags     (maxLag+1)x1 double [double]
%       Lag axis: samples by default, or seconds if 'Fs' is supplied.
%     info     1x1 struct [struct]
%       Fields:
%         .variance      R(0) before any acf normalisation (process variance)
%         .method        method actually used ('lyapunov' | 'psi')
%         .Poles .Zeros  roots of A and B
%         .IsStable      all(|Poles| < 1)
%         .NoiseVariance sigma_w^2
%         .integralTime  sum(R)/R(0) style integral timescale in lag units
%                        (0.5 + sum_{k>=1} rho(k)), one-sided, samples/seconds
%         .dt            lag step (1 sample, or 1/Fs seconds)
%         .psiTerms      psi-weights used (Method="psi"; NaN otherwise)
%
%   See also: arma2psd, spec2acv, psd2arma, synthTimeSeries, tsAcf.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (spectral)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%
%   Example
%     a = [1 -1.2 0.6]; b = [1 -0.5];
%     [R, k] = arma2acv(b, a, 30, 'NoiseVariance', 2);
%     stem(k, R); xlabel('lag'); ylabel('\gamma(k)');
%
%   Method (state-space)
%     Write the ARMA(p,q) in companion state-space form with
%       T = [phi , I; 0]  (r x r, r = max(p,q+1)),  R = [1; theta_1..theta_q; 0],
%     driven by w. The stationary state covariance P solves the discrete
%     Lyapunov equation P = T P T' + sigma_w^2 R R' (solved by a stable
%     doubling iteration with a Kronecker fallback). Then
%       gamma(k) = e1' * T^k * P * e1,
%     because the first state component is x[n]. This is exact (no
%     truncation) for any stationary ARMA.

    narginchk(3, inf);
    b = b(:).';  a = a(:).';
    validateattributes(maxLag, {'numeric'}, {'scalar','integer','nonnegative'}, ...
        mfilename, 'maxLag');

    ip = inputParser; ip.FunctionName = mfilename;
    ip.addParameter('NoiseVariance', 1, @(v) isscalar(v) && v > 0);
    ip.addParameter('Output', 'acv', @(s) any(strcmpi(char(s), {'acv','acf'})));
    ip.addParameter('Method', 'lyapunov', @(s) any(strcmpi(char(s), {'lyapunov','psi'})));
    ip.addParameter('PsiTerms', [], @(v) isempty(v) || (isscalar(v) && v >= 2));
    ip.addParameter('Fs', [], @(v) isempty(v) || (isscalar(v) && v > 0));
    ip.parse(varargin{:});
    o = ip.Results;

    % normalise leading AR coefficient to 1
    if a(1) == 0, error('arma2acv:badAR', 'a(1) must be nonzero.'); end
    b = b / a(1);  a = a / a(1);

    poles = roots(a);
    if any(abs(poles) >= 1 - 1e-12)
        error('arma2acv:nonstationary', ...
            'ARMA process is non-stationary (a root of A lies on/outside the unit circle).');
    end

    p = numel(a) - 1;  q = numel(b) - 1;
    ar = -a(2:end);                     % x_t = sum ar_i x_{t-i} + ...
    ma =  b(2:end);
    s2 = o.NoiseVariance;

    if strcmpi(o.Method, 'psi')
        [R, psiTerms] = local_acvPsi(ar, ma, s2, maxLag, poles, o.PsiTerms);
        methodUsed = 'psi';
    else
        R = local_acvLyapunov(ar, ma, s2, maxLag);
        psiTerms = NaN;
        methodUsed = 'lyapunov';
    end
    R = R(:);

    variance = R(1);
    if strcmpi(o.Output, 'acf')
        if ~(variance > 0)
            error('arma2acv:zeroVariance', 'R(0) <= 0; cannot form the ACF.');
        end
        R = R / variance;
    end

    if isempty(o.Fs)
        lags = (0:maxLag)';  dt = 1;
    else
        lags = (0:maxLag)' / o.Fs;  dt = 1/o.Fs;
    end

    % one-sided integral timescale in lag units: (0.5 + sum_{k>=1} rho_k)*dt
    if strcmpi(o.Output, 'acf')
        rho = R;                     % R already normalised to R(0)=1
    else
        rho = R / variance;
    end
    integralTime = (0.5 + sum(rho(2:end))) * dt;

    info = struct();
    info.variance      = variance;
    info.method        = methodUsed;
    info.Poles         = poles;
    info.Zeros         = roots(b);
    info.IsStable      = all(abs(poles) < 1);
    info.NoiseVariance = s2;
    info.integralTime  = integralTime;
    info.dt            = dt;
    info.psiTerms      = psiTerms;
end

% ======================================================================
function R = local_acvLyapunov(ar, ma, s2, maxLag)
%   Exact ARMA autocovariance via the state covariance P of the companion
%   state-space form and the propagation gamma(k) = e1' T^k P e1.
    p = numel(ar);  q = numel(ma);
    r = max(p, q+1);
    phi = zeros(r,1); phi(1:p) = ar;
    Rv  = zeros(r,1); Rv(1) = 1; Rv(2:1+q) = ma;
    T = zeros(r); T(:,1) = phi; T(1:r-1,2:r) = eye(r-1);
    QQ = s2 * (Rv*Rv');

    P = local_dlyap(T, QQ);

    R = zeros(maxLag+1, 1);
    col = P(:,1);                    % P*e1
    R(1) = col(1);                   % gamma(0)
    for k = 1:maxLag
        col = T*col;                 % T^k * P * e1
        R(k+1) = col(1);
    end
end

% ======================================================================
function [R, nPsi] = local_acvPsi(ar, ma, s2, maxLag, poles, nPsiReq)
%   ARMA autocovariance from MA(inf) psi-weights:
%   gamma(k) = s2 * sum_{j>=0} psi_j psi_{j+k}, truncated at nPsi terms.
    if isempty(nPsiReq)
        rmax = max(abs(poles));
        if rmax <= 0 || ~isfinite(rmax)
            nPsi = max(maxLag + 50, 200);
        else
            % want rmax^nPsi ~ 1e-6 (amplitude); tail in gamma ~ 1e-12
            nPsi = ceil(log(1e-6) / log(rmax));
            nPsi = max(nPsi, maxLag + 50);
        end
        nPsi = min(nPsi, 1e5);
    else
        nPsi = round(nPsiReq);
    end
    nPsi = max(nPsi, maxLag + 1);

    p = numel(ar);  q = numel(ma);
    psi = zeros(nPsi, 1);  psi(1) = 1;
    for k = 1:nPsi-1
        v = 0;
        for i = 1:min(p,k), v = v + ar(i)*psi(k-i+1); end
        if k <= q, v = v + ma(k); end
        psi(k+1) = v;
    end

    R = zeros(maxLag+1, 1);
    for k = 0:maxLag
        R(k+1) = s2 * (psi(1:nPsi-k)' * psi(k+1:nPsi));
    end
end

% ======================================================================
function P = local_dlyap(T, Q)
%   Discrete Lyapunov P = T P T' + Q via a doubling iteration (stable for a
%   stable T), with a Kronecker-solve fallback. (Same routine as tsForecast.)
    r = size(T,1);
    A = T; P = Q; converged = false;
    for it = 1:80 %#ok<NASGU>
        Pnew = P + A*P*A';
        A    = A*A;
        if norm(Pnew - P, 'fro') <= 1e-15*max(norm(Pnew,'fro'), 1)
            P = Pnew; converged = true; break;
        end
        P = Pnew;
    end
    if ~converged || any(~isfinite(P(:)))
        P = reshape((eye(r*r) - kron(T,T)) \ Q(:), r, r);
    end
    P = 0.5*(P + P');
end
