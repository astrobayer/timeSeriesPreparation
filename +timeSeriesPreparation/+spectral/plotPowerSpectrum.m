function varargout = plotPowerSpectrum(varargin)
%PLOTPOWERSPECTRUM  Publication-quality power/amplitude spectra of time series.
%
%   ------------------------------------------------------------------
%   INPUTS
%   ------------------------------------------------------------------
%     varargin  1xV cell [mixed]
%       Series specs + name/value options. A series is either T,X
%       (numeric time vector or scalar sampling rate in Hz, followed by
%       data) or a cell {T_or_fs, X[, label]}. T may be numeric, datetime
%       or duration. See the in-file help for the full name/value list
%       (Type, Window, SegmentLength, NAvg, Overlap, LombMethod,
%       Oversample, MaxFreq, Confidence, FAP, NPeaks, XScale/YScale,
%       Unit, Title, Axes, ShowSpectralWindow, ...).
%
%   ------------------------------------------------------------------
%   OUTPUTS
%   ------------------------------------------------------------------
%     PEAKS   1xS struct [struct array]
%       Per-series peak table with fields .label (char), .frequency (Nx1
%       double, Hz), .amplitude (Nx1 double). Empty unless 'NPeaks'>0.
%     SPEC    1xS struct [struct array]
%       Per-series spectrum: .label, .frequency (Mx1 double, Hz), .power
%       (Mx1, PSD unit^2/Hz), .amplitude (Mx1, unit), .method
%       ('fft'|'lomb-scargle'), .fs, .dof, .nseg, .variance, .fapLevels
%       (struct|[]), .spectralWindow (Mx1|[]).
%     H       1x1 struct [struct]
%       Graphics handles: .figure, .axes, .windowAxes, .lines (Sx1),
%       .peakMarkers, .ciBars, .fapLines, .legend.
%
%   See also: allanVariance, spec2acv, psd2arma.
%
%   ------------------------------------------------------------------
%   Toolbox : sigtools (spectral)
%   Author  : Generated by Claude Opus 4.8 (Anthropic)
%   Date    : 2026-07-15  (build time-of-day not available in this environment)
%   ------------------------------------------------------------------
%
%   plotPowerSpectrum(T, X)                 one series, time vector T
%   plotPowerSpectrum({T1,X1},{FS2,X2},...) several series; first cell
%                                           element is a time vector (same
%                                           size as X), a scalar sampling
%                                           rate in Hz, a datetime vector,
%                                           or a duration (vector = time
%                                           stamps, scalar = sample step).
%                                           Optional third element: label.
%   [PEAKS, SPEC, H] = plotPowerSpectrum(...)
%
%   Base MATLAB only (no toolboxes). Evenly sampled, gap-free series use a
%   (Welch-averaged) windowed FFT periodogram; series with NaN gaps or
%   uneven sampling use a Lomb-Scargle periodogram (generalized/floating-
%   mean by default). Consistent scaling in both branches:
%       'psd'       one-sided power spectral density [unit^2/Hz]
%       'amplitude' sinusoid amplitude spectrum      [unit]
%   so a sinusoid A*sin(2*pi*f0*t) peaks at ~A in the amplitude spectrum
%   regardless of the sampling scheme.
%
%   Name-value options
%   ------------------ estimation ------------------------------------------
%     'Type'          'psd' (default) | 'amplitude'
%     'Frequencies'   custom frequency vector [Hz] (forces Lomb-Scargle)
%     'Detrend'       'linear' (default) | 'mean' | 'none'
%     'Window'        'hann' (default) | 'hamming' | 'blackman' |
%                     'blackmanharris' | 'nuttall' | 'flattop' | 'kaiser' |
%                     'tukey' | 'gauss' | 'bartlett' | 'rect'/'none'
%                     (FFT branch; cosine-sum windows in periodic form)
%     'WindowParam'   Kaiser beta (8.6) | Tukey ratio (0.5) | Gauss sigma (0.4)
%     'SegmentLength' Welch segment length in samples ([] = whole record)
%     'NAvg'          alternative to SegmentLength: number of averages
%     'Overlap'       Welch segment overlap fraction (default 0.5)
%     'LombMethod'    'gls' (default, floating mean) | 'classic'
%     'Oversample'    frequency oversampling of the default LS grid (4)
%     'MaxFreq'       upper frequency limit of the default grid [Hz]
%     'NyquistMode'   dt statistic defining the default fmax = 0.5/dt*:
%                     'median' (default) | 'min' | 'mean'
%     'UniformTol'    relative dt tolerance for the uniformity test (1e-6)
%   ------------------ significance ----------------------------------------
%     'Confidence'    e.g. 0.95: chi-square confidence bar for FFT/Welch
%                     estimates (dof = 2*K segments, approximate for
%                     overlapping segments)
%     'FAP'           vector of false-alarm probabilities, e.g. [0.05 0.01]:
%                     horizontal significance levels for Lomb-Scargle series
%     'FAPMethod'     'analytic' (default): closed-form approximation with
%                     M independent frequencies ~ T_span*f_max.
%                     'bootstrap': permutation test -- data are shuffled
%                     over the fixed sampling times NBootstrap times and
%                     the max-periodogram distribution over the searched
%                     grid defines the levels. Robust to the sampling
%                     pattern; null hypothesis is WHITE noise (shuffling
%                     destroys autocorrelation -- red-noise records will
%                     look overly significant with either method).
%     'NBootstrap'    number of bootstrap realizations (default 1000;
%                     FAP*NBootstrap should be >= 10, so FAP = 0.01 needs
%                     >= 1000 realizations)
%   ------------------ peaks ------------------------------------------------
%     'NPeaks'          number of highest peaks to return/mark (default 0)
%     'MinPeakDistance' minimum peak separation [Hz]; default 1/T_span
%                       (Rayleigh resolution), so oversampled sidebins of
%                       one peak are not returned twice
%   ------------------ display ----------------------------------------------
%     'XScale'/'YScale'    'log' (default) | 'linear'
%     'Unit'               unit string of X for axis labels (e.g. 'nT')
%     'Title'              plot title
%     'Axes'               target axes ([] = new figure)
%     'ShowSpectralWindow' true/false: lower panel with the normalized
%                          spectral window |W(f)|^2 of the sampling pattern
%                          of each Lomb-Scargle series (judge alias peaks!)
%
%   Outputs
%     PEAKS  struct array per series: .label, .frequency, .amplitude
%            (N highest distinct maxima, parabolic sub-bin refinement)
%     SPEC   struct array per series: .label, .frequency, .power,
%            .amplitude, .method, .fs, .dof, .nseg, .variance,
%            .fapLevels (LS), .spectralWindow (LS)
%     H      graphics handles: .figure, .axes, .windowAxes, .lines,
%            .peakMarkers, .ciBars, .fapLines, .legend
%
%   Example
%     fs = 100;  t1 = (0:1/fs:20)';
%     x1 = 1.0*sin(2*pi*3*t1) + 0.4*randn(size(t1));  x1(400:520) = NaN;
%     t2 = sort(20*rand(1500,1));
%     x2 = 2.0*sin(2*pi*7*t2) + 0.6*randn(size(t2));
%     [pk,S,h] = plotPowerSpectrum({t1,x1,'gapped'},{t2,x2,'uneven'}, ...
%         'Type','amplitude','NPeaks',3,'FAP',[0.01], ...
%         'ShowSpectralWindow',true,'Unit','nT');

% ---------------------------------------------------------------- parsing
[series, opts] = parseInputs(varargin{:});
nSer = numel(series);

% ------------------------------------------------------------- processing
spec = struct('label',{},'frequency',{},'power',{},'amplitude',{}, ...
              'method',{},'fs',{},'dof',{},'nseg',{},'variance',{}, ...
              'fapLevels',{},'spectralWindow',{},'rayleigh',{});
for s = 1:nSer
    spec(s) = analyseSeries(series(s), opts); %#ok<AGROW>
end
anyLS = any(strcmp({spec.method},'lomb-scargle'));

% ------------------------------------------------------------------ axes
h = struct('figure',[],'axes',[],'windowAxes',gobjects(0), ...
           'lines',gobjects(nSer,1),'peakMarkers',gobjects(0), ...
           'ciBars',gobjects(0),'fapLines',gobjects(0),'legend',gobjects(0));
showWin = opts.ShowSpectralWindow && anyLS && isempty(opts.Axes);
if isempty(opts.Axes)
    h.figure = figure('Color','w','Units','centimeters', ...
        'Position',[2 2 16 10 + 3*showWin],'PaperPositionMode','auto');
    if showWin
        h.axes      = axes('Parent',h.figure,'Position',[0.12 0.34 0.84 0.60]);
        h.windowAxes= axes('Parent',h.figure,'Position',[0.12 0.10 0.84 0.17]);
    else
        h.axes = axes('Parent',h.figure);
    end
else
    h.axes = opts.Axes; h.figure = ancestor(h.axes,'figure');
    set(h.figure,'Color','w'); showWin = false;
end
ax = h.axes;  hold(ax,'on');

cols = lines(max(nSer,7));
pick = @(s) ternary(strcmpi(opts.Type,'psd'), spec(s).power, spec(s).amplitude);

% ------------------------------------------------------------------ lines
for s = 1:nSer
    h.lines(s) = plot(ax, spec(s).frequency, pick(s), '-', ...
        'Color', cols(s,:), 'LineWidth', 1.2, 'DisplayName', spec(s).label);
end

% ------------------------------------------------- FAP significance levels
if ~isempty(opts.FAP)
    for s = 1:nSer
        lv = spec(s).fapLevels;                 % struct: .fap .psd .amp
        if isempty(lv), continue; end
        y  = ternary(strcmpi(opts.Type,'psd'), lv.psd, lv.amp);
        fr = spec(s).frequency([1 end]);
        for k = 1:numel(y)
            hf = plot(ax, fr, [y(k) y(k)], '--', 'Color', cols(s,:), ...
                'LineWidth', 0.8, 'HandleVisibility','off');
            h.fapLines(end+1) = hf; %#ok<AGROW>
            text(ax, fr(end), y(k), sprintf(' %g%%', 100*(1-lv.fap(k))), ...
                'Color', cols(s,:), 'FontSize', 8, ...
                'VerticalAlignment','middle','Clipping','off');
        end
    end
end

% ------------------------------------------------------------------ peaks
peaks = struct('label',{},'frequency',{},'amplitude',{});
if opts.NPeaks > 0
    for s = 1:nSer
        mpd = opts.MinPeakDistance;
        if isempty(mpd), mpd = spec(s).rayleigh; end
        [pf, pa] = topPeaks(spec(s).frequency, pick(s), opts.NPeaks, mpd);
        peaks(s).label     = spec(s).label; %#ok<AGROW>
        peaks(s).frequency = pf;            %#ok<AGROW>
        peaks(s).amplitude = pa;            %#ok<AGROW>
        hp = plot(ax, pf, pa, 'v', 'MarkerSize', 6, ...
            'MarkerEdgeColor', cols(s,:)*0.6, 'MarkerFaceColor', cols(s,:), ...
            'HandleVisibility','off');
        h.peakMarkers(end+1) = hp; %#ok<AGROW>
    end
end

% ------------------------------------------------------ styling main axes
set(ax, 'XScale', opts.XScale, 'YScale', opts.YScale, ...
    'FontName','Helvetica','FontSize',11,'LineWidth',0.9, ...
    'TickDir','out','TickLength',[0.012 0.012],'Box','on','Layer','top', ...
    'XMinorTick','on','YMinorTick','on');
grid(ax,'on'); set(ax,'GridAlpha',0.12,'MinorGridAlpha',0.05);
u = strtrim(opts.Unit);
if strcmpi(opts.Type,'psd')
    yl = sprintf('Power spectral density (%s^2 Hz^{-1})', ternaryStr(u,'unit'));
else
    yl = sprintf('Amplitude (%s)', ternaryStr(u,'unit'));
end
ylabel(ax, yl, 'FontSize', 12);
if ~isempty(opts.Title), title(ax, opts.Title, 'FontWeight','normal'); end
if nSer > 1 || ~isempty(series(1).label)
    h.legend = legend(ax, h.lines, 'Location','best'); set(h.legend,'Box','off');
end

% -------------------------------------------- chi-square confidence bars
if ~isempty(opts.Confidence)
    drawnow;                                    % settle axis limits
    xl = get(ax,'XLim'); yliml = get(ax,'YLim');
    nb = 0;
    for s = 1:nSer
        if ~strcmp(spec(s).method,'fft'), continue; end
        c   = opts.Confidence;  k = spec(s).dof;
        lo  = k / chi2invBase(1-(1-c)/2, k);    % multiplicative CI factors
        hi  = k / chi2invBase((1-c)/2,   k);
        if strcmpi(opts.Type,'amplitude'), lo = sqrt(lo); hi = sqrt(hi); end
        if strcmpi(opts.XScale,'log')
            xpos = 10^(log10(xl(1)) + (0.06 + 0.05*nb)*diff(log10(xl)));
        else
            xpos = xl(1) + (0.06 + 0.05*nb)*diff(xl);
        end
        if strcmpi(opts.YScale,'log')
            yref = 10^(log10(yliml(1)) + 0.85*diff(log10(yliml)));
        else
            yref = yliml(1) + 0.85*diff(yliml);
        end
        hb = plot(ax, [xpos xpos], yref*[lo hi], '-', 'Color', cols(s,:), ...
            'LineWidth', 1.4, 'HandleVisibility','off');
        plot(ax, xpos, yref, 'o', 'MarkerSize',3, 'MarkerFaceColor',cols(s,:), ...
            'MarkerEdgeColor','none','HandleVisibility','off');
        if nb == 0
            text(ax, xpos, yref*hi, sprintf('  %g%%',100*c), ...
                'FontSize',8,'Color',[0.25 0.25 0.25], ...
                'VerticalAlignment','bottom');
        end
        h.ciBars(end+1) = hb; nb = nb + 1; %#ok<AGROW>
    end
end

% --------------------------------------------------- spectral-window panel
if showWin
    axw = h.windowAxes; hold(axw,'on');
    for s = 1:nSer
        if isempty(spec(s).spectralWindow), continue; end
        plot(axw, spec(s).frequency, spec(s).spectralWindow, '-', ...
            'Color', cols(s,:), 'LineWidth', 0.9);
    end
    set(axw,'XScale',opts.XScale,'YScale','log', ...
        'FontName','Helvetica','FontSize',10,'LineWidth',0.9, ...
        'TickDir','out','Box','on','XMinorTick','on');
    grid(axw,'on'); set(axw,'GridAlpha',0.12);
    ylabel(axw,'|W(f)|^2','FontSize',11);
    xlabel(axw,'Frequency (Hz)','FontSize',12);
    linkaxes([ax axw],'x'); set(ax,'XTickLabel',[]);
    hold(axw,'off');
else
    xlabel(ax,'Frequency (Hz)','FontSize',12);
end
hold(ax,'off');

% --------------------------------------------------------------- outputs
if nargout >= 1, varargout{1} = peaks; end
if nargout >= 2, varargout{2} = rmfieldSafe(spec,'rayleigh'); end
if nargout >= 3, varargout{3} = h; end
end

% ========================================================================
function [series, opts] = parseInputs(varargin)
series = struct('t',{},'x',{},'label',{});
i = 1;
while i <= numel(varargin) && ~(ischar(varargin{i}) || ...
      (isstring(varargin{i}) && isscalar(varargin{i})))
    a = varargin{i};
    if iscell(a)
        assert(numel(a) >= 2, 'Cell input must be {time_or_fs, data(, label)}.');
        s.t = a{1}; s.x = a{2};
        if numel(a) >= 3, s.label = char(a{3}); else, s.label = ''; end
        series(end+1) = s; %#ok<AGROW>
        i = i + 1;
    elseif isnumeric(a) || isdatetime(a) || isduration(a)
        assert(i+1 <= numel(varargin) && isnumeric(varargin{i+1}), ...
               'Time/fs argument must be followed by a numeric data vector.');
        s.t = a; s.x = varargin{i+1}; s.label = '';
        series(end+1) = s; %#ok<AGROW>
        i = i + 2;
    else
        error('plotPowerSpectrum:badInput','Unrecognised input #%d.', i);
    end
end
assert(~isempty(series), 'No time series supplied.');
for k = 1:numel(series)
    if isempty(series(k).label), series(k).label = sprintf('Series %d',k); end
end

p = inputParser; p.FunctionName = 'plotPowerSpectrum';
addParameter(p,'Type','psd',@(v)any(strcmpi(v,{'psd','amplitude'})));
addParameter(p,'Frequencies',[],@(v)isnumeric(v)&&isvector(v)&&all(v>0));
addParameter(p,'NPeaks',0,@(v)isnumeric(v)&&isscalar(v)&&v>=0);
addParameter(p,'MinPeakDistance',[],@(v)isempty(v)||(isscalar(v)&&v>=0));
addParameter(p,'Detrend','linear',@(v)any(strcmpi(v,{'none','mean','linear'})));
addParameter(p,'Window','hann',@(v)any(strcmpi(v,{'hann','hamming', ...
    'blackman','blackmanharris','nuttall','flattop','kaiser','tukey', ...
    'gauss','bartlett','rect','rectangular','none'})));
addParameter(p,'WindowParam',[],@(v)isempty(v)||(isscalar(v)&&isfinite(v)));
addParameter(p,'SegmentLength',[],@(v)isempty(v)||(isscalar(v)&&v>=8));
addParameter(p,'NAvg',[],@(v)isempty(v)||(isscalar(v)&&v>=1));
addParameter(p,'Overlap',0.5,@(v)isscalar(v)&&v>=0&&v<1);
addParameter(p,'LombMethod','gls',@(v)any(strcmpi(v,{'gls','classic'})));
addParameter(p,'Oversample',4,@(v)isscalar(v)&&v>=1);
addParameter(p,'MaxFreq',[],@(v)isempty(v)||(isscalar(v)&&v>0));
addParameter(p,'NyquistMode','median',@(v)any(strcmpi(v,{'median','min','mean'})));
addParameter(p,'UniformTol',1e-6,@(v)isscalar(v)&&v>0);
addParameter(p,'Confidence',[],@(v)isempty(v)||(isscalar(v)&&v>0&&v<1));
addParameter(p,'FAP',[],@(v)isempty(v)||(isnumeric(v)&&all(v>0&v<1)));
addParameter(p,'FAPMethod','analytic',@(v)any(strcmpi(v,{'analytic','bootstrap'})));
addParameter(p,'NBootstrap',1000,@(v)isscalar(v)&&v>=10);
addParameter(p,'XScale','log',@(v)any(strcmpi(v,{'log','linear'})));
addParameter(p,'YScale','log',@(v)any(strcmpi(v,{'log','linear'})));
addParameter(p,'Unit','',@(v)ischar(v)||isstring(v));
addParameter(p,'Title','',@(v)ischar(v)||isstring(v));
addParameter(p,'Axes',[],@(v)isempty(v)||isgraphics(v,'axes'));
addParameter(p,'ShowSpectralWindow',false,@(v)islogical(v)||ismember(v,[0 1]));
parse(p, varargin{i:end});
opts = p.Results;
opts.Unit = char(opts.Unit); opts.Title = char(opts.Title);
end

% ========================================================================
function out = analyseSeries(ser, opts)
x = double(ser.x(:));  traw = ser.t(:);

% Time input: datetime / duration / numeric; scalar => rate or step
if isdatetime(traw)
    t = seconds(traw - traw(1));
elseif isduration(traw)
    if isscalar(traw), t = (0:numel(x)-1)' * seconds(traw);
    else,              t = seconds(traw - traw(1));
    end
elseif isscalar(traw)
    assert(traw > 0, 'Sampling rate must be positive.');
    t = (0:numel(x)-1)'/double(traw);
else
    t = double(traw);
end
assert(numel(t) == numel(x), ...
    '"%s": time vector and data must have equal length.', ser.label);

% Drop NaN/Inf samples (data gaps), sort by time
good = isfinite(t) & isfinite(x);
t = t(good); x = x(good);
[t, is] = sort(t); x = x(is);
N = numel(x);
assert(N >= 8, '"%s": fewer than 8 valid samples.', ser.label);

dt = diff(t);  dt(dt == 0) = [];
mdt = median(dt);
switch lower(opts.NyquistMode)
    case 'min',  dtNyq = min(dt);
    case 'mean', dtNyq = mean(dt);
    otherwise,   dtNyq = mdt;
end
fsEff = 1/mdt;                                % density scale (robust)
isUniform = all(abs(dt - mdt) < opts.UniformTol*mdt);
Tspan = t(end) - t(1);

% Detrend
switch lower(opts.Detrend)
    case 'mean',   x = x - mean(x);
    case 'linear', c = polyfit(t, x, 1); x = x - polyval(c, t);
end
varx = var(x);

out = struct('label',ser.label,'frequency',[],'power',[],'amplitude',[], ...
    'method','','fs',fsEff,'dof',[],'nseg',[],'variance',varx, ...
    'fapLevels',[],'spectralWindow',[],'rayleigh',1/Tspan);

customF = ~isempty(opts.Frequencies);
if isUniform && ~customF
    % ------------- Welch-averaged windowed FFT periodogram --------------
    if ~isempty(opts.SegmentLength)
        L = min(round(opts.SegmentLength), N);
    elseif ~isempty(opts.NAvg) && opts.NAvg > 1
        L = floor(N / (1 + (opts.NAvg-1)*(1-opts.Overlap)));
        L = max(L, 8);
    else
        L = N;
    end
    step   = max(1, round(L*(1-opts.Overlap)));
    starts = 1:step:(N-L+1);
    if L == N, starts = 1; end
    K = numel(starts);

    w  = makeWindow(opts.Window, L, opts.WindowParam);
    nH = floor(L/2);
    acc = zeros(nH,1);
    for kk = 1:K
        seg = x(starts(kk):starts(kk)+L-1);
        seg = seg - mean(seg);                 % per-segment demean (Welch)
        X   = fft(seg .* w);
        acc = acc + abs(X(2:nH+1)).^2;
    end
    P2 = acc / K;                              % averaged |X|^2, DC skipped
    f  = (1:nH)' * fsEff / L;
    psd = 2*P2 / (fsEff * sum(w.^2));
    amp = 2*sqrt(P2) / sum(w);
    if mod(L,2) == 0, psd(end) = psd(end)/2;  amp(end) = amp(end)/2; end
    out.method = 'fft';  out.nseg = K;
    out.dof = 2*K;   % approximate for overlapping segments (conservative)
    out.rayleigh = fsEff / L;                  % actual bin resolution
else
    % --------------------- Lomb-Scargle periodogram ---------------------
    if customF
        f = sort(double(opts.Frequencies(:)));
    else
        df   = 1/(opts.Oversample * Tspan);
        fmax = 0.5 / dtNyq;
        if ~isempty(opts.MaxFreq), fmax = min(fmax, opts.MaxFreq); end
        f = (df:df:fmax)';
        assert(~isempty(f), '"%s": empty frequency grid.', ser.label);
    end
    if strcmpi(opts.LombMethod,'gls')
        A2 = lombGLS(t, x, f);                 % fitted sinusoid amplitude^2
    else
        P  = lombClassic(t, x, f);
        A2 = 4*P/N;
    end
    P   = N*A2/4;                              % classical-equivalent power
    psd = 2*P / fsEff;
    amp = sqrt(A2);
    out.method = 'lomb-scargle';  out.nseg = 1;  out.dof = 2;

    % FAP significance levels
    if ~isempty(opts.FAP) && N > 5
        fap = sort(opts.FAP(:),'descend');
        if strcmpi(opts.FAPMethod,'bootstrap')
            % Permutation bootstrap: shuffle x over the fixed sampling
            % times (white-noise null hypothesis), record the maximum
            % periodogram value over the *searched* grid per realization.
            B = round(opts.NBootstrap);
            if min(fap)*B < 10
                warning('plotPowerSpectrum:fapResolution', ...
                    ['"%s": NBootstrap = %d gives < 10 exceedances for ' ...
                     'FAP = %g; level is noisy. Increase NBootstrap.'], ...
                    ser.label, B, min(fap));
            end
            mx = zeros(B,1);
            for bb = 1:B
                xb = x(randperm(N));
                if strcmpi(opts.LombMethod,'gls')
                    mx(bb) = max(lombGLS(t, xb, f));
                else
                    mx(bb) = max(4*lombClassic(t, xb, f)/N);
                end
            end
            A2L = quantileBase(mx, 1 - fap);
            fapMethod = 'bootstrap';
        else
            % Analytic approximation, M independent frequencies ~ T*df
            M  = max(round(Tspan * (f(end)-f(1))), 1);
            pnL = 1 - (1 - (1 - fap).^(1/M)).^(2/(N-3));
            pnL = min(max(pnL,0), 1-1e-12);
            A2L = 2*varx*pnL;                  % pn -> sinusoid amplitude^2
            fapMethod = 'analytic';
        end
        out.fapLevels = struct('fap',fap, 'method',fapMethod, ...
            'psd', 2*(N*A2L/4)/fsEff, 'amp', sqrt(A2L));
    end

    % Spectral window of the sampling pattern (normalized, |W(0)|^2 = 1)
    out.spectralWindow = spectralWindow(t, f);
end

if ~customF && ~isempty(opts.MaxFreq)
    keep = f <= opts.MaxFreq;
    f = f(keep); psd = psd(keep); amp = amp(keep);
    if ~isempty(out.spectralWindow), out.spectralWindow = out.spectralWindow(keep); end
end
out.frequency = f;  out.power = psd;  out.amplitude = amp;
end

% ========================================================================
function [A2, pn] = lombGLS(t, x, f)
% Generalized (floating-mean) Lomb-Scargle, unweighted
% (Zechmeister & Kuerster 2009). Returns fitted sinusoid amplitude^2 and
% normalized power pn = fraction of variance explained, chunk-vectorised.
N = numel(t);
A2 = zeros(size(f));  pn = zeros(size(f));
Ybar = mean(x);  YY = mean(x.^2) - Ybar^2;  YY = max(YY, eps);
chunk = max(1, floor(4e6 / N));
for i0 = 1:chunk:numel(f)
    idx = i0:min(i0+chunk-1, numel(f));
    th  = t * (2*pi*f(idx)');                 % N x m
    c = cos(th);  s = sin(th);
    C  = mean(c,1);          S  = mean(s,1);
    YC = (x'*c)/N - Ybar*C;  YS = (x'*s)/N - Ybar*S;
    CC = mean(c.^2,1) - C.^2;
    SS = mean(s.^2,1) - S.^2;
    CS = mean(c.*s,1) - C.*S;
    D  = CC.*SS - CS.^2;  D(abs(D) < eps) = eps;
    a  = (YC.*SS - YS.*CS)./D;
    b  = (YS.*CC - YC.*CS)./D;
    A2(idx) = a.^2 + b.^2;
    pn(idx) = (SS.*YC.^2 + CC.*YS.^2 - 2*CS.*YC.*YS) ./ (YY*D);
end
pn = min(max(pn,0),1);
end

% ========================================================================
function P = lombClassic(t, x, f)
% Classical Lomb-Scargle periodogram (fixed mean), chunk-vectorised.
N = numel(t);  x = x - mean(x);  P = zeros(size(f));
chunk = max(1, floor(4e6 / N));
for i0 = 1:chunk:numel(f)
    idx = i0:min(i0+chunk-1, numel(f));
    w   = 2*pi*f(idx)';
    wt  = t * w;
    tau = atan2(sum(sin(2*wt),1), sum(cos(2*wt),1)) ./ (2*w);
    arg = wt - ones(N,1)*(w.*tau);
    C = cos(arg);  S = sin(arg);
    xC = x' * C;   xS = x' * S;
    CC = sum(C.^2,1);  SS = sum(S.^2,1);
    CC(CC < eps) = eps;  SS(SS < eps) = eps;
    P(idx) = 0.5*(xC.^2 ./ CC + xS.^2 ./ SS);
end
end

% ========================================================================
function W = spectralWindow(t, f)
% Normalized spectral window |W(f)|^2 of the sampling pattern.
N = numel(t);  W = zeros(size(f));
chunk = max(1, floor(4e6 / N));
for i0 = 1:chunk:numel(f)
    idx = i0:min(i0+chunk-1, numel(f));
    th  = t * (2*pi*f(idx)');
    W(idx) = (sum(cos(th),1).^2 + sum(sin(th),1).^2) / N^2;
end
end

% ========================================================================
function [pf, pa] = topPeaks(f, y, nPk, minDist)
% N highest distinct local maxima (greedy min-distance selection) with
% 3-point parabolic sub-bin refinement.
y = y(:); f = f(:);
i = find(y(2:end-1) > y(1:end-2) & y(2:end-1) >= y(3:end)) + 1;
if isempty(i), pf = []; pa = []; return; end
[~, order] = sort(y(i), 'descend');
i = i(order);
sel = [];
for k = 1:numel(i)
    if isempty(sel) || all(abs(f(i(k)) - f(sel)) >= minDist)
        sel(end+1) = i(k); %#ok<AGROW>
        if numel(sel) == nPk, break; end
    end
end
pf = zeros(numel(sel),1);  pa = zeros(numel(sel),1);
for k = 1:numel(sel)
    j = sel(k);
    y1 = y(j-1); y2 = y(j); y3 = y(j+1);
    den = y1 - 2*y2 + y3;
    if abs(den) > eps, d = max(min(0.5*(y1-y3)/den, 0.5), -0.5);
    else,              d = 0;
    end
    pf(k) = f(j) + d * 0.5*(f(j+1) - f(j-1));
    pa(k) = y2 - 0.25*(y1 - y3)*d;
end
end

% ========================================================================
function w = makeWindow(name, N, prm)
% Window generation in base MATLAB. Cosine-sum windows use the PERIODIC
% form (denominator N), preferable for spectral analysis.
n = (0:N-1)';  rp = n/N;  rs = n/(N-1);
switch lower(name)
    case 'hann'
        w = 0.5 - 0.5*cos(2*pi*rp);
    case 'hamming'
        w = 0.54 - 0.46*cos(2*pi*rp);
    case 'blackman'
        w = 0.42 - 0.5*cos(2*pi*rp) + 0.08*cos(4*pi*rp);
    case 'blackmanharris'                     % 4-term, -92 dB sidelobes
        a = [0.35875 0.48829 0.14128 0.01168];
        w = a(1) - a(2)*cos(2*pi*rp) + a(3)*cos(4*pi*rp) - a(4)*cos(6*pi*rp);
    case 'nuttall'
        a = [0.355768 0.487396 0.144232 0.012604];
        w = a(1) - a(2)*cos(2*pi*rp) + a(3)*cos(4*pi*rp) - a(4)*cos(6*pi*rp);
    case 'flattop'                            % minimal scalloping loss
        a = [0.21557895 0.41663158 0.277263158 0.083578947 0.006947368];
        w = a(1) - a(2)*cos(2*pi*rp) + a(3)*cos(4*pi*rp) ...
                 - a(4)*cos(6*pi*rp) + a(5)*cos(8*pi*rp);
    case 'kaiser'                             % prm = beta (default 8.6)
        if isempty(prm), prm = 8.6; end
        w = besseli(0, prm*sqrt(1 - (2*rs - 1).^2)) / besseli(0, prm);
    case 'tukey'                              % prm = taper ratio (0.5)
        if isempty(prm), prm = 0.5; end
        prm = max(min(prm,1),0);
        w = ones(N,1);
        if prm > 0
            L = floor(prm*(N-1)/2);  k = (0:L)';
            taper = 0.5*(1 + cos(pi*(2*k/(prm*(N-1)) - 1)));
            w(1:L+1) = taper;  w(end-L:end) = flipud(taper);
        end
    case 'gauss'                              % prm = sigma (default 0.4)
        if isempty(prm), prm = 0.4; end
        w = exp(-0.5*((2*rs - 1)/prm).^2);
    case 'bartlett'
        w = 1 - abs(2*rs - 1);
    otherwise                                 % 'rect'/'rectangular'/'none'
        w = ones(N,1);
end
end

% ========================================================================
function x = chi2invBase(p, k)
% Inverse chi-square CDF in base MATLAB: solve gammainc(x/2, k/2) = p.
fun = @(x) gammainc(max(x,0)/2, k/2) - p;
hiB = k + 20*sqrt(2*k) + 100;                 % safe upper bracket
x = fzero(fun, [1e-12, hiB]);
end

% ========================================================================
function q = quantileBase(v, p)
% Sample quantiles with linear interpolation (base MATLAB; quantile()
% belongs to the Statistics Toolbox). Matches MATLAB's default method.
v = sort(v(:));  n = numel(v);  p = p(:);
pos = p*n + 0.5;                              % MATLAB quantile convention
lo  = max(floor(pos), 1);  hi = min(lo+1, n);
w   = pos - lo;  w = min(max(w,0),1);
q   = (1-w).*v(lo) + w.*v(hi);
end

