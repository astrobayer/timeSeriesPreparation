    % ------------------------------------- reparametrisation robustness
    function fitAlwaysStationary(tc)
        % Reparametrised fit must return a stationary AR and invertible MA
        % for every realisation, even near-unit-root data.
        rng(200);
        for trial = 1:8
            x = local_simARMA([0.7; 0.2], 0.5, 1500);   % close to non-stationary
            m = timeSeriesPreparation.tsmodels.tsFitArima(x, 2, 0, 1);
            arRoots = abs(roots([1; -m.ar(:)]));
            maRoots = abs(roots([1; m.ma(:)]));
            tc.verifyLessThan(max(arRoots), 1 + 1e-6, 'AR must be stationary');
            tc.verifyLessThan(max(maRoots), 1 + 1e-6, 'MA must be invertible');
        end
    end

    function higherOrderRecovery(tc)
        % ARMA(3,2): the reparametrised multi-start optimiser should recover
        % the mean coefficients across several seeds (the old single-start
        % fminsearch was unreliable here).
        truePhi = [0.3; 0.2; -0.15]; trueTh = [0.4; -0.2];
        arEst = zeros(3, 6); maEst = zeros(2, 6);
        for r = 1:6
            rng(300 + r);
            x = local_simARMA(truePhi, trueTh, 3000);
            m = timeSeriesPreparation.tsmodels.tsFitArima(x, 3, 0, 2);
            arEst(:, r) = m.ar(:); maEst(:, r) = m.ma(:);
        end
        tc.verifyEqual(mean(arEst, 2), truePhi, 'AbsTol', 0.12);
        tc.verifyEqual(mean(maEst, 2), trueTh,  'AbsTol', 0.15);
    end

    function seCoversTruth(tc)
        % The true parameter should lie within ~3 standard errors of the
        % estimate on average - a direct check that stdErr is well scaled.
        phi = 0.6; nHit = 0; N = 12;
        for r = 1:N
            rng(400 + r);
            x = local_simAR(phi, 1500);
            m = timeSeriesPreparation.tsmodels.tsFitArima(x, 1, 0, 0);
            se = m.stdErr(end);                    % SE of the AR coefficient
            if isfinite(se) && abs(m.ar(1) - phi) <= 3*se
                nHit = nHit + 1;
            end
        end
        tc.verifyGreaterThanOrEqual(nHit, N - 2);  % almost always covered
    end

    function dlyapStableNearUnitRoot(tc)
        % The doubling Lyapunov solver must still give a finite likelihood for
